"""Bake the approved Osteophage Blockbench project into the native Java model."""
from base64 import b64decode
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / "docs/art/osteophage"
ASSETS = ROOT / "src/main/resources/assets/hemomancy"
JAVA = ROOT / "src/main/java/com/vincenthuto/hemomancy/client/model/entity/mob/animal/OsteophageMesh.java"
FACES = ("north", "east", "south", "west", "up", "down")


def relative(point, parent):
    return (point[0] - parent[0], parent[1] - point[1], point[2] - parent[2])


def rotation(node):
    x, y, z = node.get("rotation", (0, 0, 0))
    return -x, y, -z


def floats(values):
    return ", ".join(f"{value:g}F" for value in values)


def export_mesh(project):
    elements = {cube["uuid"]: cube for cube in project["elements"]}
    root, = project["outliner"]
    width, height = (project["resolution"][axis] for axis in ("width", "height"))
    lines = [
        "package com.vincenthuto.hemomancy.client.model.entity.mob.animal;",
        "", "import java.util.List;", "import java.util.Map;", "",
        "import net.minecraft.client.model.geom.ModelPart;",
        "import net.minecraft.client.model.geom.PartPose;",
        "import net.minecraft.util.Mth;", "",
        "/** Generated by tools/model_export/osteophage.py from OsteophageVulture.bbmodel. */",
        "final class OsteophageMesh {",
        f"    static final int TEXTURE_WIDTH = {width};",
        f"    static final int TEXTURE_HEIGHT = {height};", "",
        "    private OsteophageMesh() {}", "",
        "    static ModelPart createRoot() {",
    ]

    def write_group(group, parent):
        name, origin = group["name"], group["origin"]
        groups = [node for node in group["children"] if isinstance(node, dict)]
        cubes = [elements[node] for node in group["children"] if isinstance(node, str)]
        for child in groups:
            write_group(child, origin)
        pose = floats((*relative(origin, parent), *rotation(group)))
        lines.append(f"        ModelPart {name} = part({pose},")
        if cubes:
            lines.append("                List.of(")
            for i, cube in enumerate(cubes):
                a, b = cube["from"], cube["to"]
                pivot = cube["origin"]
                low = relative((a[0], b[1], a[2]), pivot)
                high = relative((b[0], a[1], b[2]), pivot)
                bounds = floats((*low, *high))
                transform = floats((*relative(pivot, origin), *rotation(cube)))
                uv = floats(value for face in FACES for value in cube["faces"][face]["uv"])
                lines.append(f"                        new OsteophageCube({bounds},")
                lines.append(f"                                {transform},")
                lines.append(f"                                {uv})" + ("," if i < len(cubes) - 1 else ""))
            lines.append("                ),")
        else:
            lines.append("                List.of(),")
        if groups:
            lines.append("                Map.ofEntries(")
            for i, child in enumerate(groups):
                key = child["name"]
                lines.append(f'                        Map.entry("{key}", {key})' + ("," if i < len(groups) - 1 else "));"))
        else:
            lines.append("                Map.of());")

    # The authored talons end near y=1.25 in the Y-up project. Minecraft's floor is at y=24.
    write_group(root, (0, 25.25, 0))
    lines.extend([
        "        return root;", "    }", "",
        "    private static ModelPart part(float x, float y, float z, float pitch, float yaw, float roll,",
        "                                  List<ModelPart.Cube> cubes, Map<String, ModelPart> children) {",
        "        ModelPart part = new ModelPart(cubes, children);",
        "        PartPose pose = PartPose.offsetAndRotation(x, y, z,",
        "                pitch * Mth.DEG_TO_RAD, yaw * Mth.DEG_TO_RAD, roll * Mth.DEG_TO_RAD);",
        "        part.setInitialPose(pose);",
        "        part.loadPose(pose);",
        "        return part;", "    }", "}", "",
    ])
    return "\n".join(lines)


def main():
    model = (ART / "OsteophageVulture.bbmodel").read_bytes()
    texture = (ART / "osteophage_vulture.png").read_bytes()
    project = json.loads(model)
    embedded = project["textures"][0]["source"].split(",", 1)[1]
    if b64decode(embedded, validate=True) != texture:
        raise ValueError("Blockbench's embedded texture differs from the PNG")
    # The packaged project and PNG sit in different directories.
    project["textures"][0]["relative_path"] = "../../../textures/entity/osteophage.png"
    project["textures"][0]["name"] = "osteophage.png"
    java = export_mesh(project)
    (ASSETS / "models/entity/bbmodel/Osteophage.bbmodel").write_text(
        json.dumps(project, indent=2) + "\n", encoding="utf-8")
    (ASSETS / "textures/entity/osteophage.png").write_bytes(texture)
    JAVA.write_text(java, encoding="utf-8")


if __name__ == "__main__":
    main()
