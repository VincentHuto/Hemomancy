"""Bake the Choir Keeper's Blockbench rig and embedded atlas into runtime assets."""
from base64 import b64decode
import json

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "src/main/resources/assets/hemomancy"

PROJECT = ASSETS / "models/entity/bbmodel/ChoirKeeperModel.bbmodel"
TEXTURE = ASSETS / "textures/entity/choir_keeper_java.png"
JAVA = ROOT / "src/main/java/com/vincenthuto/hemomancy/client/model/entity/mob/animal/ChoirKeeperMesh.java"


FACES = ("north", "east", "south", "west", "up", "down")


def relative(point, parent):
    return (point[0] - parent[0], parent[1] - point[1], point[2] - parent[2])


def rotation(node):
    x, y, z = node.get("rotation", (0, 0, 0))
    return -x, y, -z


def floats(values):
    return ", ".join(f"{value:g}F" for value in values)


def export_mesh(project, *,
                package="com.vincenthuto.hemomancy.client.model.entity.mob.animal",
                mesh_name="ChoirKeeperMesh",
                source="tools/model_export/export_choir_keeper_java.py from ChoirKeeperModel.bbmodel",
                split_parts=False,
                reverse_winding=False):
    elements = {cube["uuid"]: cube for cube in project["elements"]}
    root, = project["outliner"]
    width, height = (project["resolution"][axis] for axis in ("width", "height"))
    lines = [
        f"package {package};",
        "", "import com.vincenthuto.hemomancy.client.model.entity.FaceUvCube;",
        "import java.util.List;", "import java.util.Map;", "",
        "import net.minecraft.client.model.geom.ModelPart;",
        "import net.minecraft.client.model.geom.PartPose;",
        "import net.minecraft.util.Mth;", "",
        f"/** Generated by {source}. */",
        f"final class {mesh_name} {{",
        f"    static final int TEXTURE_WIDTH = {width};",
        f"    static final int TEXTURE_HEIGHT = {height};", "",
        f"    private {mesh_name}() {{}}", "",
        "    static ModelPart createRoot() {",
    ]
    if split_parts:
        lines.extend([f"        return build_{root['name']}();", "    }", ""])

    def write_group(group, parent):
        name, origin = group["name"], group["origin"]
        groups = [node for node in group["children"] if isinstance(node, dict)]
        cubes = [elements[node] for node in group["children"] if isinstance(node, str)]
        for child in groups:
            write_group(child, origin)
        pose = floats((*relative(origin, parent), *rotation(group)))
        if split_parts:
            lines.append(f"    private static ModelPart build_{name}() {{")
            lines.append(f"        return part({pose},")
        else:
            lines.append(f"        ModelPart {name} = part({pose},")
        if cubes:
            lines.append("                List.of(")
            for i, cube in enumerate(cubes):
                a, b = cube["from"], cube["to"]
                pivot = cube["origin"]
                low = relative((a[0], b[1], a[2]), pivot)
                high = relative((b[0], a[1], b[2]), pivot)
                bounds = floats((*low, *high))
                transform = floats((*relative(pivot, origin), *rotation(cube)))
                uv = ", ".join(
                    floats(cube["faces"][face]["uv"]) if face in cube["faces"] else "Float.NaN, 0F, 0F, 0F"
                    for face in FACES
                )
                lines.append(f"                        new FaceUvCube(TEXTURE_WIDTH, TEXTURE_HEIGHT, {bounds},")
                winding = ", true" if reverse_winding else ""
                lines.append(f"                                {transform}{winding},")
                lines.append(f"                                {uv})" + ("," if i < len(cubes) - 1 else ""))
            lines.append("                ),")
        else:
            lines.append("                List.of(),")
        if groups:
            lines.append("                Map.ofEntries(")
            for i, child in enumerate(groups):
                key = child["name"]
                child_part = f"build_{key}()" if split_parts else key
                lines.append(f'                        Map.entry("{key}", {child_part})'
                             + ("," if i < len(groups) - 1 else "));"))
        else:
            lines.append("                Map.of());")
        if split_parts:
            lines.extend(["    }", ""])

    write_group(root, (0, 24, 0))
    if not split_parts:
        lines.extend([f"        return {root['name']};", "    }", ""])
    lines.extend([
        "    private static ModelPart part(float x, float y, float z, float pitch, float yaw, float roll,",
        "                                  List<ModelPart.Cube> cubes, Map<String, ModelPart> children) {",
        "        ModelPart part = new ModelPart(cubes, children);",
        "        PartPose pose = PartPose.offsetAndRotation(x, y, z,",
        "                pitch * Mth.DEG_TO_RAD, yaw * Mth.DEG_TO_RAD, roll * Mth.DEG_TO_RAD);",
        "        part.setInitialPose(pose);",
        "        part.loadPose(pose);",
        "        return part;", "    }", "}", "",
    ])
    return "\n".join(lines)


def resolve_outliner(project):
    groups = {group["uuid"]: group for group in project["groups"]}

    def resolve(node):
        if isinstance(node, str):
            return node
        return {**groups[node["uuid"]], "children": [resolve(child) for child in node["children"]]}

    project["outliner"] = [resolve(node) for node in project["outliner"]]


def main():
    project = json.loads(PROJECT.read_text(encoding="utf-8"))
    resolve_outliner(project)
    java = export_mesh(project)
    texture, = project["textures"]
    png = b64decode(texture["source"].split(",", 1)[1], validate=True)
    JAVA.write_text(java, encoding="utf-8")
    TEXTURE.write_bytes(png)


if __name__ == "__main__":
    main()
