"""Bake the editable Prism Cuttle project into its Java model mesh."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROJECT = ROOT / "src/main/resources/assets/hemomancy/models/entity/bbmodel/PrismCuttleModel.bbmodel"
JAVA = ROOT / "src/main/java/com/vincenthuto/hemomancy/client/model/entity/mob/aquatic/PrismCuttleMesh.java"
FACE_ORDER = ("north", "east", "south", "west", "up", "down")


def reflected(point):
    x, y, z = point
    return x, -y, z


def delta(point, origin):
    return reflected(tuple(value - anchor for value, anchor in zip(point, origin, strict=True)))


def angles(entry):
    pitch, yaw, roll = entry.get("rotation", (0, 0, 0))
    return -pitch, yaw, -roll


def floats(values):
    return ", ".join(f"{(value or 0):g}F" for value in values)


class Mesh:
    def __init__(self, project):
        self.elements = {item["uuid"]: item for item in project["elements"]}
        self.groups = {item["uuid"]: item for item in project["groups"]}
        self.size = project["resolution"]
        self.lines = []

    def cube(self, element, parent_origin, animated=False):
        low, high = element["from"], element["to"]
        pivot = element["origin"]
        minimum = delta((low[0], high[1], low[2]), pivot)
        maximum = delta((high[0], low[1], high[2]), pivot)
        uv = [value for side in FACE_ORDER for value in element["faces"][side]["uv"]]
        position = delta(pivot, parent_origin)
        rotation = (0, 0, 0) if animated else angles(element)
        return (
            f"new FaceUvCube({self.size['width']}, {self.size['height']}, {floats(minimum + maximum)},\n"
            f"                        {floats(position + rotation)},\n"
            f"                        {floats(uv)})"
        )

    def add_part(self, name, position, rotation, cubes, children):
        geometry = ",\n                ".join(cubes)
        entries = ",\n                ".join(f'Map.entry("{child}", {child})' for child in children)
        cube_list = f"List.of(\n                {geometry})" if cubes else "List.of()"
        child_map = f"Map.ofEntries(\n                {entries})" if children else "Map.of()"
        self.lines.append(
            f"        ModelPart {name} = part({floats(position + rotation)},\n"
            f"                {cube_list},\n                {child_map});"
        )

    def group(self, node, parent_origin):
        group = self.groups[node["uuid"]]
        name, origin = group["name"], group["origin"]
        cubes, children = [], []
        for entry in node["children"]:
            if isinstance(entry, dict):
                children.append(self.group(entry, origin))
                continue
            element = self.elements[entry]
            if name in ("left_fin", "right_fin"):
                # The fin panels rotate independently around their authored roots.
                panel = element["name"]
                pivot = element["origin"]
                self.add_part(panel, delta(pivot, origin), angles(element),
                              [self.cube(element, pivot, animated=True)], [])
                children.append(panel)
            else:
                cubes.append(self.cube(element, origin))
        self.add_part(name, delta(origin, parent_origin), angles(group), cubes, children)
        return name


def main():
    project = json.loads(PROJECT.read_text(encoding="utf-8"))
    mesh = Mesh(project)
    root, = project["outliner"]
    # Minecraft's living renderer places model Y=24 at the entity's feet.
    # Lower the authored mesh by 1.25 units to center the mantle in its hitbox.
    root_name = mesh.group(root, (0, 25.25, 0))
    parts = "\n".join(mesh.lines)
    JAVA.write_text(f"""package com.vincenthuto.hemomancy.client.model.entity.mob.aquatic;

import com.vincenthuto.hemomancy.client.model.entity.FaceUvCube;
import java.util.List;
import java.util.Map;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.util.Mth;

/** Generated by tools/model_export/prism_cuttle.py from PrismCuttleModel.bbmodel. */
final class PrismCuttleMesh {{
    private PrismCuttleMesh() {{}}

    static ModelPart createRoot() {{
{parts}
        return {root_name};
    }}

    private static ModelPart part(float x, float y, float z, float pitch, float yaw, float roll,
                                  List<ModelPart.Cube> cubes, Map<String, ModelPart> children) {{
        ModelPart part = new ModelPart(cubes, children);
        PartPose pose = PartPose.offsetAndRotation(x, y, z,
                pitch * Mth.DEG_TO_RAD, yaw * Mth.DEG_TO_RAD, roll * Mth.DEG_TO_RAD);
        part.setInitialPose(pose);
        part.loadPose(pose);
        return part;
    }}
}}
""", encoding="utf-8")


if __name__ == "__main__":
    main()
