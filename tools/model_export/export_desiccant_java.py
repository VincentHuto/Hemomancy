"""Export the Desiccant's box-UV Blockbench project to the vanilla model layer."""

from base64 import b64decode
import json
from math import radians
import re

from export_choir_keeper_java import ASSETS, ROOT, floats, relative, rotation


PROJECT = ROOT / "docs/art/desiccant/Desiccant.bbmodel"
TEXTURE = ASSETS / "textures/entity/desiccant/model_desiccant.png"
PACKAGE = "com.vincenthuto.hemomancy.client.model.entity.mob.arthropod"
JAVA = ROOT / "src/main/java" / PACKAGE.replace(".", "/") / "DesiccantMesh.java"


def export_mesh(project):
    cubes = {cube["uuid"]: cube for cube in project["elements"]}
    width, height = (project["resolution"][axis] for axis in ("width", "height"))
    root, = project["outliner"]
    lines = [
        f"package {PACKAGE};",
        "",
        "import net.minecraft.client.model.geom.PartPose;",
        "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
        "import net.minecraft.client.model.geom.builders.LayerDefinition;",
        "import net.minecraft.client.model.geom.builders.MeshDefinition;",
        "import net.minecraft.client.model.geom.builders.PartDefinition;",
        "",
        "/** Generated by tools/model_export/export_desiccant_java.py. */",
        "final class DesiccantMesh {",
        "    private DesiccantMesh() {}",
        "",
        "    static LayerDefinition createBodyLayer() {",
        "        var mesh = new MeshDefinition();",
        "        PartDefinition root = mesh.getRoot();",
    ]

    def write_group(group, parent, parent_var):
        origin = group["origin"]
        name = re.sub("[^a-z0-9]+", "_", group["name"].lower())
        groups = [node for node in group["children"] if isinstance(node, dict)]
        prefix = f"        PartDefinition {parent_var}_{name} = " if groups else "        "
        lines.append(f'{prefix}{parent_var}.addOrReplaceChild("{name}", CubeListBuilder.create()')
        for node in group["children"]:
            if isinstance(node, dict):
                continue
            cube = cubes.pop(node)
            assert cube["box_uv"] and not cube.get("mirror_uv") and not any(rotation(cube))
            low, high = cube["from"], cube["to"]
            start = relative((low[0], high[1], low[2]), origin)
            size = tuple(b - a for a, b in zip(low, high))
            u, v = cube["uv_offset"]
            lines.append(f"                .texOffs({u}, {v}).addBox({floats((*start, *size))})")
        offset = relative(origin, parent)
        angles = tuple(radians(angle) for angle in rotation(group))
        pose = f"offsetAndRotation({floats((*offset, *angles))})" if any(angles) else f"offset({floats(offset)})"
        lines.append(f"                , PartPose.{pose});")
        for child in groups:
            write_group(child, origin, f"{parent_var}_{name}")

    write_group(root, (0, 24, 0), "root")
    assert not cubes
    lines.extend([f"        return LayerDefinition.create(mesh, {width}, {height});", "    }", "}", ""])
    return "\n".join(lines)


def main():
    project = json.loads(PROJECT.read_text(encoding="utf-8"))
    texture, = project["textures"]
    png = b64decode(texture["source"].split(",", 1)[1], validate=True)
    assert png == PROJECT.with_name("desiccant.png").read_bytes()
    JAVA.write_text(export_mesh(project), encoding="utf-8")
    TEXTURE.write_bytes(png)


if __name__ == "__main__":
    main()
