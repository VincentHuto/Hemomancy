"""Bake the approved Fungling and Hunter Fungus Blockbench sources into entity layers and textures."""

import io
import json
import re
from base64 import b64decode
from math import radians
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = "com.vincenthuto.hemomancy.client.model.entity.mob"
JAVA = ROOT / "src/main/java" / Path(*PACKAGE.split("."))
ASSETS = ROOT / "src/main/resources/assets/hemomancy"


def identifier(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def java_float(value):
    return f"{value:.8f}".rstrip("0").rstrip(".") + "F" if abs(value) > 1e-8 else "0F"


def java_args(values):
    return ", ".join(map(java_float, values))


def pivot_offset(pivot, parent):
    return [pivot[0] - parent[0], parent[1] - pivot[1], pivot[2] - parent[2]]


def emit_layer(model, package, class_name, source):
    elements = {cube["uuid"]: cube for cube in model["elements"]}
    lines = [
        f"package {package};", "",
        "import net.minecraft.client.model.geom.PartPose;",
        "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
        "import net.minecraft.client.model.geom.builders.LayerDefinition;",
        "import net.minecraft.client.model.geom.builders.MeshDefinition;",
        "import net.minecraft.client.model.geom.builders.PartDefinition;", "",
        f"// Generated by tools/model_export/fungling.py from {source}.",
        f"final class {class_name} {{",
        f"\tprivate {class_name}() {{}}", "",
        "\tstatic LayerDefinition createBodyLayer() {",
        "\t\tMeshDefinition mesh = new MeshDefinition();",
        "\t\tPartDefinition root = mesh.getRoot();",
    ]

    def emit_part(name, parent, pivot, parent_pivot, rotation, cubes, has_children, path):
        offset = java_args(pivot_offset(pivot, parent_pivot))
        x, y, z = map(radians, rotation)
        pose = (f"PartPose.offsetAndRotation({offset}, {java_args((-x, y, -z))})"
                if any(rotation) else f"PartPose.offset({offset})")
        assignment = f"PartDefinition {path} = " if has_children else ""
        lines.append(f'\t\t{assignment}{parent}.addOrReplaceChild("{name}", CubeListBuilder.create()')
        for cube in cubes:
            assert cube["box_uv"] and not cube.get("mirror_uv") and not cube.get("inflate")
            x, y, z = cube["from"]
            tx, ty, tz = cube["to"]
            args = java_args((x - pivot[0], pivot[1] - ty, z - pivot[2], tx - x, ty - y, tz - z))
            u, v = cube["uv_offset"]
            lines.append(f"\t\t\t\t.texOffs({u}, {v}).addBox({args})")
        lines[-1] += f", {pose});"

    def emit_group(group, parent, parent_pivot, path):
        name = identifier(group["name"])
        pivot = group["origin"]
        groups = [child for child in group["children"] if isinstance(child, dict)]
        cubes = [elements[child] for child in group["children"] if isinstance(child, str)]
        direct = [cube for cube in cubes if not any(cube["rotation"])]
        rotated = [cube for cube in cubes if any(cube["rotation"])]
        emit_part(name, parent, pivot, parent_pivot, group["rotation"], direct, groups or rotated, path)
        for cube in rotated:
            emit_part(identifier(cube["name"]), path, cube["origin"], pivot, cube["rotation"],
                      [cube], False, "")
        for child in groups:
            emit_group(child, path, pivot, f'{path}_{identifier(child["name"])}')

    emit_group(model["outliner"][0], "root", (0, 24, 0), "rig")
    size = model["resolution"]
    lines.extend([f'\t\treturn LayerDefinition.create(mesh, {size["width"]}, {size["height"]});',
                  "\t}", "}", ""])
    return "\n".join(lines)


def write_glow(model, png, path):
    image = Image.open(io.BytesIO(png)).convert("RGBA")
    glow = Image.new("RGBA", image.size)
    for cube in model["elements"]:
        if cube["name"] == "Amber eye":
            faces, colors = ["north"], {(226, 141, 67), (255, 194, 104), (255, 231, 175)}
        elif cube["name"] in {"Rolled red brim", "Fleshy dome", "Off-center crown"}:
            faces, colors = cube["faces"], {(245, 186, 117)}
        else:
            continue
        for face in faces:
            u0, v0, u1, v1 = cube["faces"][face]["uv"]
            for y in range(min(v0, v1), max(v0, v1)):
                for x in range(min(u0, u1), max(u0, u1)):
                    pixel = image.getpixel((x, y))
                    if pixel[:3] in colors:
                        glow.putpixel((x, y), pixel)
    glow.save(path)


def bake(slug, category, class_name, texture_name, project_name):
    source = Path("docs/art") / slug / f"{slug}.bbmodel"
    model = json.loads((ROOT / source).read_text(encoding="utf-8"))
    png = (ROOT / source.with_suffix(".png")).read_bytes()
    texture = model["textures"][0]
    assert b64decode(texture["source"].split(",", 1)[1]) == png
    destination = ASSETS / "textures/entity" / slug
    (JAVA / category / f"{class_name}.java").write_text(
        emit_layer(model, f"{PACKAGE}.{category}", class_name, source.as_posix()), encoding="utf-8", newline="\n")
    (destination / f"{texture_name}.png").write_bytes(png)
    if slug == "fungling":
        write_glow(model, png, destination / f"{texture_name}_glow.png")
    texture["name"] = f"{texture_name}.png"
    texture["relative_path"] = f"../../../textures/entity/{slug}/{texture_name}.png"
    (ASSETS / "models/entity/bbmodel" / f"{project_name}.bbmodel").write_text(
        json.dumps(model, indent=2) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    bake("fungling", "animal", "FunglingMesh", "model_fungling", "FunglingModel")
    bake("hunter_fungus", "monster", "HunterFungusMesh", "hunter_fungus", "HunterFungusModel")
