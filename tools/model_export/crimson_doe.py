"""Export the Crimson Doe's editable Blockbench rig and its matching glow atlas."""

from collections import defaultdict
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'src/main/resources/assets/hemomancy'
MODEL = ASSETS / 'models/entity/bbmodel/CrimsonDoeRedesign.bbmodel'
TEXTURES = ASSETS / 'textures/entity/crimson_doe'
JAVA = ROOT / 'src/main/java/com/vincenthuto/hemomancy/client/model/entity/mob/animal/CrimsonDoeMesh.java'
FACES = ('north', 'east', 'south', 'west', 'up', 'down')


def xyz(point, origin):
    # Blockbench is Y-up, while entity model coordinates grow downward.
    return [sign * (value - pivot) for value, pivot, sign in zip(point, origin, (1, -1, 1))]


def vec(values):
    return ', '.join(f'{float(value)}F' for value in values)


def export_mesh(project):
    elements = {element['uuid']: element for element in project['elements']}
    root, = project['outliner']
    width, height = (project['resolution'][axis] for axis in ('width', 'height'))
    lines = [
        'package com.vincenthuto.hemomancy.client.model.entity.mob.animal;', '',
        'import java.util.List;', 'import java.util.Map;', '',
        'import net.minecraft.client.model.geom.ModelPart;', 'import net.minecraft.client.model.geom.PartPose;',
        'import net.minecraft.util.Mth;', '',
        '/** Generated by tools/model_export/crimson_doe.py from CrimsonDoeRedesign.bbmodel. */',
        'final class CrimsonDoeMesh {',
        f'    static final int TEXTURE_WIDTH = {width};',
        f'    static final int TEXTURE_HEIGHT = {height};',
        '',
        '    private CrimsonDoeMesh() {}', '',
        '    static ModelPart createRoot() {',
    ]
    variables = defaultdict(int)

    # Source groups must be constructed before their parents so ModelPart can keep its collections private.
    def write_node(node, parent_origin, name=None):
        origin = node['origin']
        position = xyz(origin, parent_origin)
        x, y, z = node.get('rotation', (0, 0, 0))
        name = name or node['name']
        variables[name] += 1
        local = f'{name}_{variables[name]}' if variables[name] > 1 else name
        kids, cubes = [], []
        for child in node.get('children', ()):
            if isinstance(child, dict):
                kids.append((child['name'], write_node(child, origin)))
            else:
                cube = elements[child]
                if any(cube.get('rotation', ())):
                    pivot = cube['name'] + '_pivot'
                    kids.append((pivot, write_node(dict(cube, pivot_only=True), origin, pivot)))
                else:
                    cubes.append(cube)
        if node.get('pivot_only'):
            cubes = [node]
            kids = []
        args = f'{vec(position)}, {vec((-x, y, -z))}'
        lines.append(f'        ModelPart {local} = part({args},')
        lines.append('                List.of(')
        for i, cube in enumerate(cubes):
            lo = xyz((cube['from'][0], cube['to'][1], cube['from'][2]), origin)
            hi = xyz((cube['to'][0], cube['from'][1], cube['to'][2]), origin)
            uv = ', '.join(', '.join(str(v) for v in cube['faces'][key]['uv']) for key in FACES)
            lines.append(f'                        new CrimsonDoeCube({vec(lo)}, {vec(hi)},')
            lines.append(f'                                {uv})' + (',' if i+1<len(cubes) else ''))
        pairs = ', '.join(f'Map.entry("{key}", {var})' for key, var in kids)
        lines.append(f'                ), Map.ofEntries({pairs}));')
        return local

    # A rotated cube is represented by a fixed child at the cube's own pivot.
    root_name = write_node(root, (0, 24, 0))
    lines += [
        f'        return {root_name};', '    }', '',
        '    private static ModelPart part(float x, float y, float z, float rx, float ry, float rz,',
        '            List<ModelPart.Cube> cubes, Map<String, ModelPart> children) {',
        '        ModelPart part = new ModelPart(cubes, children);',
        '        PartPose pose = PartPose.offsetAndRotation(x, y, z, rx * Mth.DEG_TO_RAD, ry * Mth.DEG_TO_RAD, rz * Mth.DEG_TO_RAD);',
        '        part.setInitialPose(pose);',
        '        part.loadPose(pose);',
        '        return part;', '    }', '}', '',
    ]
    return '\n'.join(lines)


def export_glow(project):
    texture = Image.open(TEXTURES / 'model_crimson_doe_redesign.png').convert('RGBA')
    glow = Image.new('RGBA', texture.size)
    crystal = {'antler_beam', 'antler_tip', 'brow_tine', 'jagged_cheek_shard'}
    for cube in project['elements']:
        name = cube['name']
        for face in cube['faces'].values():
            x0, y0, x1, y1 = face['uv']
            for y in range(y0, y1):
                for x in range(x0, x1):
                    r, g, b, a = texture.getpixel((x, y))
                    if name in crystal and r >= 150:
                        glow.putpixel((x, y), (r // 2, g // 4, b // 4, a))
                    elif name in {'jugular', 'jugular_fork'} and r >= 150:
                        glow.putpixel((x, y), (r // 3, g // 5, b // 5, a))
                    elif name == 'skull' and (r, g, b) == (184, 90, 99):
                        glow.putpixel((x, y), (92, 23, 28, a))
    glow.save(TEXTURES / 'model_crimson_doe_redesign_glow.png')


if __name__ == '__main__':
    project = json.loads(MODEL.read_text(encoding='utf-8'))
    JAVA.write_text(export_mesh(project), encoding='utf-8')
    export_glow(project)
