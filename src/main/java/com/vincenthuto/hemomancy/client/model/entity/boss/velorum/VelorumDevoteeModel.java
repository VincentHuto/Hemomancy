	/** The shape's channels: the figure by joint group as it rises, then the reach or the grip over it. */
	static float[] shapeChannels(int figurePose, float rise, float reach, float grip, float age) {
		float[] a = new float[CHANNELS];
		float legs = 1.0F - HemoEasing.ramp(rise, 0.0F, 0.5F);
		float body = 1.0F - HemoEasing.ramp(rise, 0.05F, 0.6F);
		float arms = 1.0F - HemoEasing.ramp(rise, 0.15F, 0.8F);
		float head = 1.0F - HemoEasing.ramp(rise, 0.4F, 1.0F);
		float alive = figure(a, figurePose, head, arms, body, legs, 0.0F);
		if (alive <= 0.0F) return a;
		float r = HemoEasing.clamp01(reach) * alive;
		a[R_ARM_X] -= 1.55F * r;
		a[R_FORE] += 0.3F * r;
		a[L_ARM_X] += 0.25F * r;
		a[BODY_X] += 0.35F * r;
		a[HEAD_X] -= 0.2F * r;
		a[R_LEG] -= 0.3F * r;
		a[R_SHIN] += 0.3F * r;
		a[L_SHIN] += 0.15F * r;
		a[SHIVER] += 0.3F * r;
		if (grip > 0.0F) grip(a, age, HemoEasing.clamp01(grip) * alive);
		return a;
	}

	/** The channels of one frame: the frozen figure by joint group, the awake stance, the walk, the blow and the grip. */
	static float[] channels(int state, int figurePose, float stateAge, float stride, float walking, float blow,
			boolean gripping, boolean hostile, float age) {
		float[] a = new float[CHANNELS];
		int pose = state == 2 ? 0 : figurePose;
		float head = 0.0F, arms = 0.0F, body = 0.0F, legs = 0.0F;
		switch (state) {
			case 0 -> {
				float t = stateAge / VelorumCongregationRules.thawTicks(figurePose);
				head = 1.0F - hitches(t * 1.2F);
				arms = 1.0F - hitches(t);
				body = 1.0F - hitches(t * 0.95F - 0.03F);
				legs = 1.0F - hitches(t * 0.9F - 0.06F);
				a[SHIVER] += HemoEasing.window(t, 0.0F, 0.05F, 0.85F, 1.0F) * (0.4F + 0.6F * crack(t));
			}
			case 2 -> {
				legs = settle(stateAge, 0.0F, 18.0F);
				body = settle(stateAge, 4.0F, 24.0F);
				arms = settle(stateAge, 6.0F, 26.0F);
				head = settle(stateAge, 10.0F, STILL_TICKS);
				a[SHIVER] += HemoEasing.window(stateAge, 0.0F, 4.0F, 20.0F, STILL_TICKS) * 0.5F;
			}
			case 4 -> head = arms = body = legs = 1.0F;
			default -> {
			}
		}
		float alive = figure(a, pose, head, arms, body, legs, hostile ? 1.0F : 0.0F);
		if (alive <= 0.0F) return a;
		walk(a, stride, walking * alive);
		if (gripping) grip(a, age, alive);
		if (blow >= 0.0F && blow < BLOW_LENGTH) blow(a, blow, alive);
		return a;
	}

	/**
	 * Lays one of the block's poses on {@code a} by joint group (1 frozen in the figure, 0 free) over the awake stance,
	 * and returns how alive the body is.
	 */
	static float figure(float[] a, int pose, float head, float arms, float body, float legs, float hunch) {
		float[] f = figure(pose);
		float alive = 1.0F - Math.max(Math.max(head, arms), Math.max(body, legs));
		a[ALIVE] = alive;
		a[FROZEN_LEGS] = legs;
		// awake: an ally stands upright and stiff, a hostile hunched with its head carried forward and its knees bent
		awake(a, 1.0F - body, 1.0F - arms, 1.0F - head, 1.0F - legs, hunch);
		a[SINK] += f[0] * legs;
		a[BODY_X] += f[1] * DEG * body;
		a[HEAD_X] += f[2] * DEG * head;
		a[R_ARM_X] += f[3] * DEG * arms;
		a[L_ARM_X] += f[4] * DEG * arms;
		a[R_FORE] += f[5] * DEG * arms;
		a[L_FORE] += f[6] * DEG * arms;
		a[R_LEG] += f[7] * DEG * legs;
		a[L_LEG] += f[8] * DEG * legs;
		a[R_SHIN] += f[9] * DEG * legs;
		a[L_SHIN] += f[10] * DEG * legs;
		return alive;
	}

	/** The awake stance, by joint group so a thawing body comes into it a group at a time. */
	static void awake(float[] a, float body, float arms, float head, float legs, float hunch) {
		a[BODY_X] += (0.05F + 0.2F * hunch) * body;
		a[HEAD_X] += (0.02F - 0.22F * hunch) * head;
		a[R_ARM_X] += (-0.14F - 0.2F * hunch) * arms;
		a[L_ARM_X] += (-0.14F - 0.2F * hunch) * arms;
		a[R_ARM_Z] += 0.06F * arms;
		a[L_ARM_Z] -= 0.06F * arms;
		a[R_FORE] += (-0.3F - 0.25F * hunch) * arms;
		a[L_FORE] += (-0.3F - 0.25F * hunch) * arms;
		a[R_LEG] += -0.16F * hunch * legs;
		a[L_LEG] += -0.16F * hunch * legs;
		a[R_SHIN] += 0.3F * hunch * legs;
		a[L_SHIN] += 0.3F * hunch * legs;
	}

	/** The short stiff walk: the gait on the legs, the arms held close with a small counter-swing, a little roll. */
	static void walk(float[] a, float stride, float w) {
		if (w <= 0.0F) return;
		float p = VelorumDevoteeGait.phase(stride);
		a[L_LEG] += VelorumDevoteeGait.thigh(p, VelorumDevoteeGait.LEFT) * w;
		a[R_LEG] += VelorumDevoteeGait.thigh(p, VelorumDevoteeGait.RIGHT) * w;
		a[L_LIFT] += VelorumDevoteeGait.lift(p, VelorumDevoteeGait.LEFT) * w;
		a[R_LIFT] += VelorumDevoteeGait.lift(p, VelorumDevoteeGait.RIGHT) * w;
		a[L_SHIN] += a[L_LIFT] * VelorumDevoteeGait.KNEE_LIFT;
		a[R_SHIN] += a[R_LIFT] * VelorumDevoteeGait.KNEE_LIFT;
		float rock = Mth.sin(p * Mth.TWO_PI);
		a[R_ARM_X] += rock * 0.08F * w;
		a[L_ARM_X] -= rock * 0.08F * w;
		a[BODY_Z] += rock * 0.03F * w;
		a[BODY_Y] -= rock * 0.04F * w;
		a[BODY_X] += 0.04F * w;
	}

	/** The grip: the arms clamped forward, braced on bent knees, leaning in and straining. */
	static void grip(float[] a, float age, float alive) {
		a[R_ARM_X] -= 1.25F * alive;
		a[L_ARM_X] -= 1.25F * alive;
		a[R_ARM_Z] -= 0.12F * alive;
		a[L_ARM_Z] += 0.12F * alive;
		a[R_FORE] -= 0.25F * alive;
		a[L_FORE] -= 0.25F * alive;
		a[BODY_X] += 0.2F * alive;
		a[HEAD_X] -= 0.15F * alive;
		a[R_LEG] -= 0.3F * alive;
		a[L_LEG] -= 0.1F * alive;
		a[R_SHIN] += 0.5F * alive;
		a[L_SHIN] += 0.3F * alive;
		a[SHIVER] += 0.6F * alive;
	}

	/**
	 * 12 / 4 / 14. Both arms rise overhead and the body arches back up onto its toes; at 12 they come down in a tick and
	 * a half with the whole body folding after them and the knees giving, carry on past the line, then it straightens.
	 */
	static void blow(float[] a, float t, float alive) {
		float arms = catmullRom(t, 0, 0, 8, -2.2F, 11.5F, -2.55F, 13.5F, -0.3F, 16, 0.1F, 22, -0.05F, 30, 0);
		a[R_ARM_X] += arms * alive;
		a[L_ARM_X] += arms * alive;
		float fore = catmullRom(t, 0, 0, 10, 0.25F, 11.5F, 0.3F, 13.5F, -0.15F, 22, -0.05F, 30, 0);
		a[R_FORE] += fore * alive;
		a[L_FORE] += fore * alive;
		a[BODY_X] += catmullRom(t, 0, 0, 9, -0.12F, 11.5F, -0.16F, 13.5F, 0.42F, 16, 0.5F, 22, 0.15F, 30, 0) * alive;
		a[HEAD_X] += catmullRom(t, 0, 0, 9, -0.15F, 11.5F, -0.18F, 13.5F, 0.25F, 17, 0.3F, 30, 0) * alive;
		float knees = catmullRom(t, 0, 0, 11.5F, -0.05F, 14, 0.5F, 17, 0.45F, 24, 0.1F, 30, 0) * alive;
		a[R_SHIN] += knees;
		a[L_SHIN] += knees;
		a[R_LEG] -= knees * 0.5F;
		a[L_LEG] -= knees * 0.5F;
		a[SINK] += catmullRom(t, 0, 0, 9, -0.6F, 11.5F, -0.7F, 13.5F, 0, 30, 0) * alive;
		a[SHIVER] += HemoEasing.pulse(t - 13.5F, 0.5F, 6.0F) * 0.8F * alive;
	}

	/** Three stiff hitches over a thaw: each cracks free in a short ease, overshoots a little and settles back. */
	static float hitches(float t) {
		return catmullRom(t, 0, 0, 0.05F, 0, 0.13F, 0.37F, 0.18F, 0.32F, 0.38F, 0.33F, 0.46F, 0.7F, 0.51F, 0.65F, 0.7F, 0.66F,
				0.78F, 1.05F, 0.84F, 0.99F, 1, 1);
	}

	/** 1 at each hitch's crack, else 0: the rime shivering off. */
	static float crack(float t) {
		return HemoEasing.pulse(t - 0.05F, 0.03F, 0.12F) + HemoEasing.pulse(t - 0.38F, 0.03F, 0.12F)
				+ HemoEasing.pulse(t - 0.7F, 0.03F, 0.12F);
	}

	/** Slowing into stillness: quick at first, then ever slower, as the cold takes it. */
	static float settle(float t, float from, float to) {
		float x = HemoEasing.clamp01((t - from) / (to - from));
		return 1.0F - (1.0F - x) * (1.0F - x) * (1.0F - x);
	}

	/** The springs, after the blend: the head a beat behind the body, the hood's drape, the cord, the cuffs. */
	static void secondary(float[] a, VelorumDevoteeAnimState m) {
		float alive = HemoEasing.clamp01(a[ALIVE]);
		float walking = m.walking();
		a[LAG_HEAD_X] = clampTrail(m.lag(0, a[BODY_X], 0.5F, 0.55F) * 0.5F) * alive;
		a[LAG_HEAD_Z] = clampTrail(m.lag(1, a[BODY_Z] + m.turn() * 0.2F, 0.5F, 0.55F) * 0.5F) * alive;
		a[HOOD_X] = clampTrail(-m.lag(2, a[BODY_X] + a[HEAD_X], 0.4F, 0.25F) * 0.8F + walking * 0.12F) * alive;
		a[HOOD_Z] = clampTrail(-m.lag(3, a[BODY_Z] + a[HEAD_Z] - m.yawTravel() * 0.5F, 0.4F, 0.25F) * 0.6F) * alive;
		a[CORD_X] = clampTrail(-m.lag(4, a[BODY_X] + a[SINK] * 0.05F, 0.5F, 0.2F) + walking * 0.15F) * alive;
		a[CORD_Z] = clampTrail(-m.lag(5, a[BODY_Z] + a[BODY_Y] - m.yawTravel() * 0.4F, 0.5F, 0.2F)) * alive;
		a[CUFF_R] = clampTrail(-m.lag(6, a[R_ARM_X] + a[R_FORE], 0.5F, 0.25F) * 0.6F) * alive;
		a[CUFF_L] = clampTrail(-m.lag(7, a[L_ARM_X] + a[L_FORE], 0.5F, 0.25F) * 0.6F) * alive;
	}

	private static float clampTrail(float value) {
		return Mth.clamp(value, -0.6F, 0.6F);
	}

	/**
	 * Lays the channels on the rig. The hips sink until the lower sole meets the floor (a frozen figure keeps the block's
	 * own sink exactly); the hood's drape, the cord and the cuffs hang as far toward plumb as the body is awake.
	 */
	void pose(float[] a, float age, float yaw, float pitch) {
		root.getAllParts().forEach(ModelPart::resetPose);
		float alive = HemoEasing.clamp01(a[ALIVE]);
		float shiver = a[SHIVER] * 0.02F;
		float shake = Mth.sin(age * 2.7F) * 0.6F + Mth.sin(age * 4.1F + 1.1F) * 0.4F;
		float legs = HemoEasing.clamp01(a[FROZEN_LEGS]);
		float ground = VelorumDevoteeGait.sink(a[L_LEG], a[L_SHIN], a[L_LIFT], a[R_LEG], a[R_SHIN], a[R_LIFT]);
		hips.y += a[SINK] + ground * (1.0F - legs);
		body.xRot += a[BODY_X] + shiver * shake;
		body.yRot += a[BODY_Y];
		body.zRot += a[BODY_Z] - shiver * shake * 0.6F;
		head.xRot += a[HEAD_X] + a[LAG_HEAD_X] + Mth.clamp(pitch, -20.0F, 20.0F) * DEG * 0.5F * alive;
		head.yRot += Mth.clamp(yaw, -30.0F, 30.0F) * DEG * 0.6F * alive;
		head.zRot += a[HEAD_Z] + a[LAG_HEAD_Z];
		rightArm.xRot += a[R_ARM_X] + shiver * shake * 1.5F;
		rightArm.zRot += a[R_ARM_Z];
		leftArm.xRot += a[L_ARM_X] - shiver * shake * 1.5F;
		leftArm.zRot += a[L_ARM_Z];
		rightForearm.xRot += a[R_FORE];
		leftForearm.xRot += a[L_FORE];
		rightLeg.xRot += a[R_LEG];
		leftLeg.xRot += a[L_LEG];
		rightShin.xRot += a[R_SHIN];
		leftShin.xRot += a[L_SHIN];
		hoodTail.xRot += -(body.xRot + head.xRot) * 0.5F * alive + a[HOOD_X];
		hoodTail.zRot += a[HOOD_Z];
		cordEnds.xRot += -(hips.xRot + body.xRot) * 0.85F * alive + a[CORD_X];
		cordEnds.zRot += -body.zRot * 0.85F * alive + a[CORD_Z];
		rightCuff.xRot += -(body.xRot + rightArm.xRot + rightForearm.xRot) * 0.85F * alive + a[CUFF_R];
		leftCuff.xRot += -(body.xRot + leftArm.xRot + leftForearm.xRot) * 0.85F * alive + a[CUFF_L];
	}
