package com.vincenthuto.hemomancy.client.model.entity.mob.animal;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.vincenthuto.hemomancy.Hemomancy;
import com.vincenthuto.hemomancy.common.entity.mob.animal.VampireBatEntity;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.util.Mth;

/**
 * Flies level with its legs trailing, leaning into climbs and turns. Hunting, it beats harder, swings its claws forward
 * and snaps its jaw. At rest it hangs by its feet, cloaked in its wings. The mesh is generated by
 * tools/model_export/vampire_bat.py.
 */
public final class VampireBatModel extends HierarchicalModel<VampireBatEntity> {
	public static final ModelLayerLocation LAYER_LOCATION = new ModelLayerLocation(Hemomancy.rloc("vampire_bat"), "main");
	private static final float CRUISE_BEAT = 0.62F;
	private static final float HUNT_BEAT = 0.95F;

	private final ModelPart root;
	private final ModelPart neck;
	private final ModelPart head;
	private final ModelPart jaw;
	private final ModelPart tailWeb;
	private final ModelPart leftEar;
	private final ModelPart rightEar;
	private final Wing leftWing;
	private final Wing rightWing;
	private final Leg leftLeg;
	private final Leg rightLeg;

	private record Wing(ModelPart shoulder, ModelPart forearm, ModelPart hand, float side) {
		static Wing of(ModelPart body, String prefix, float side) {
			ModelPart shoulder = body.getChild(prefix + "_wing");
			ModelPart forearm = shoulder.getChild(prefix + "_forearm");
			return new Wing(shoulder, forearm, forearm.getChild(prefix + "_hand"), side);
		}

		/** Positive folds down toward the belly on both sides. */
		void pose(float shoulderAngle, float forearmAngle, float handAngle) {
			shoulder.zRot = shoulderAngle * side;
			forearm.zRot = forearmAngle * side;
			hand.zRot = handAngle * side;
		}
	}

	private record Leg(ModelPart thigh, ModelPart shin, ModelPart foot) {
		static Leg of(ModelPart body, String prefix) {
			ModelPart thigh = body.getChild(prefix + "_leg");
			ModelPart shin = thigh.getChild(prefix + "_shin");
			return new Leg(thigh, shin, shin.getChild(prefix + "_foot"));
		}

		void pose(float thighAngle, float shinAngle, float footAngle) {
			thigh.xRot = thighAngle;
			shin.xRot = shinAngle;
			foot.xRot = footAngle;
		}
	}

	public VampireBatModel(ModelPart bakedRoot) {
		root = bakedRoot.getChild("root");
		ModelPart body = root.getChild("body");
		neck = body.getChild("neck");
		head = neck.getChild("head");
		jaw = head.getChild("jaw");
		tailWeb = body.getChild("tail_web");
		leftEar = head.getChild("left_ear");
		rightEar = head.getChild("right_ear");
		leftWing = Wing.of(body, "left", 1.0F);
		rightWing = Wing.of(body, "right", -1.0F);
		leftLeg = Leg.of(body, "left");
		rightLeg = Leg.of(body, "right");
	}

	public static LayerDefinition createBodyLayer() {
		return VampireBatMesh.createBodyLayer();
	}

	@Override
	public ModelPart root() {
		return root;
	}

	@Override
	public void setupAnim(VampireBatEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
		root.getAllParts().forEach(ModelPart::resetPose);
		if (entity.isResting()) {
			hang(ageInTicks);
			return;
		}
		float partialTick = ageInTicks - entity.tickCount;
		fly(entity.isHunting(), ageInTicks, entity.flightPitch(partialTick), entity.flightBank(partialTick));
		// The bite: the jaw clamps shut and the head jerks down for a few ticks.
		float bite = entity.biteSnap(partialTick);
		if (bite > 0.0F) {
			jaw.xRot = Mth.lerp(bite, jaw.xRot, 0.05F);
			head.xRot += 0.35F * bite;
		}
		head.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.6F;
		neck.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.4F;
		head.xRot += headPitch * Mth.DEG_TO_RAD * 0.5F;
	}

	private void fly(boolean hunting, float age, float pitch, float bank) {
		float beat = age * (hunting ? HUNT_BEAT : CRUISE_BEAT);
		float rise = Mth.sin(beat);
		float lift = Mth.cos(beat);
		float reach = hunting ? 0.85F : 0.62F;
		// The arm leads; the forearm and hand trail it, folding on the way up and straightening on the power stroke.
		float shoulder = -0.1F - reach * rise;
		float forearm = 0.2F + 0.28F * lift;
		float hand = 0.22F + 0.5F * lift;
		leftWing.pose(shoulder, forearm, hand);
		rightWing.pose(shoulder, forearm, hand);

		root.xRot = -pitch + (hunting ? 0.28F : 0.06F);
		root.zRot = bank;
		root.y += rise * 1.1F;
		neck.xRot += (hunting ? -0.25F : 0.0F) + lift * 0.05F;
		head.xRot += hunting ? -0.1F : 0.08F;

		if (hunting) {
			// Claws thrown forward under the chest, jaw snapping.
			float clutch = Mth.sin(age * 0.45F) * 0.12F;
			leftLeg.pose(-0.35F + clutch, 0.55F, -0.5F);
			rightLeg.pose(-0.35F - clutch, 0.55F, -0.5F);
			jaw.xRot = 0.55F + 0.35F * Math.max(0.0F, Mth.sin(age * 0.7F));
			tailWeb.xRot += 0.5F;
			leftEar.xRot -= 0.25F;
			rightEar.xRot -= 0.25F;
		} else {
			float trail = lift * 0.08F;
			leftLeg.pose(1.15F + trail, 0.2F, -0.9F);
			rightLeg.pose(1.15F - trail, 0.2F, -0.9F);
			jaw.xRot += Math.max(0.0F, Mth.sin(age * 0.05F) - 0.7F) * 1.6F;
			tailWeb.xRot += lift * 0.1F;
		}
	}

	private void hang(float age) {
		// Head down, feet up to the block overhead, and the wings closed around the belly like a cloak.
		root.xRot = Mth.HALF_PI;
		root.y += 5.0F;
		float breath = Mth.sin(age * 0.06F);
		leftWing.pose(1.1F + breath * 0.02F, 1.0F, 0.85F);
		rightWing.pose(1.1F + breath * 0.02F, 1.0F, 0.85F);
		leftLeg.pose(Mth.HALF_PI, 0.0F, 0.0F);
		rightLeg.pose(Mth.HALF_PI, 0.0F, 0.0F);
		neck.xRot -= 0.25F;
		head.xRot -= 0.35F;
		tailWeb.xRot += 0.2F;
	}

	@Override
	public void renderToBuffer(PoseStack poseStack, VertexConsumer buffer, int packedLight, int packedOverlay, int packedColor) {
		root.render(poseStack, buffer, packedLight, packedOverlay, packedColor);
	}
}
