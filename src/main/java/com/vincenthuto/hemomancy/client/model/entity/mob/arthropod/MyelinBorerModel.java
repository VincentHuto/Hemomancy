package com.vincenthuto.hemomancy.client.model.entity.mob.arthropod;

import com.vincenthuto.hemomancy.Hemomancy;
import com.vincenthuto.hemomancy.common.entity.mob.arthropod.MyelinBorerEntity;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.util.Mth;

/**
 * A travelling wave runs down the segments while it crawls, the legs step in pairs out of phase, and the palps feel
 * ahead. The mesh is generated by tools/model_export/myelin_borer.py.
 */
public final class MyelinBorerModel extends HierarchicalModel<MyelinBorerEntity> {
	public static final ModelLayerLocation LAYER_LOCATION = new ModelLayerLocation(Hemomancy.rloc("myelin_borer"), "main");
	private static final int RINGS = 5;
	private static final int LEG_PAIRS = 4;

	private final ModelPart root;
	private final ModelPart body;
	private final ModelPart head;
	private final ModelPart[] rings = new ModelPart[RINGS];
	private final ModelPart[][] legs = new ModelPart[LEG_PAIRS][2];
	private final ModelPart[] palps = new ModelPart[2];

	public MyelinBorerModel(ModelPart bakedRoot) {
		root = bakedRoot.getChild("root");
		body = root.getChild("body");
		head = body.getChild("head");
		ModelPart ring = body;
		for (int i = 0; i < RINGS; i++) {
			ring = ring.getChild("ring" + i);
			rings[i] = ring;
		}
		for (int i = 0; i < LEG_PAIRS; i++) {
			ModelPart holder = i == 0 ? body : rings[i - 1];
			legs[i][0] = holder.getChild("left_leg" + i);
			legs[i][1] = holder.getChild("right_leg" + i);
		}
		palps[0] = head.getChild("left_palp");
		palps[1] = head.getChild("right_palp");
	}

	public static LayerDefinition createBodyLayer() {
		return MyelinBorerMesh.createBodyLayer();
	}

	@Override
	public ModelPart root() {
		return root;
	}

	@Override
	public void setupAnim(MyelinBorerEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
		root.getAllParts().forEach(ModelPart::resetPose);
		float crawling = entity.isCrawling() ? 1.0F : Math.min(1.0F, limbSwingAmount * 2.0F);
		float phase = ageInTicks * 0.55F;
		body.y -= crawling * Math.abs(Mth.sin(phase)) * 0.3F;
		head.yRot = Mth.sin(phase + 0.9F) * (0.06F + 0.12F * crawling);
		head.xRot = Mth.sin(phase * 0.7F) * 0.04F;
		for (int i = 0; i < RINGS; i++) {
			rings[i].yRot = Mth.sin(phase - i * 0.75F) * (0.035F + crawling * 0.09F);
			rings[i].xRot = Mth.sin(phase - i * 0.75F - 0.6F) * (0.025F + crawling * 0.055F);
		}
		for (int i = 0; i < LEG_PAIRS; i++) {
			for (int side = 0; side < 2; side++) {
				float sign = side == 0 ? 1.0F : -1.0F;
				float step = Mth.sin(phase * 1.6F + i * 1.4F + side * Mth.PI);
				legs[i][side].yRot += sign * step * (0.08F + crawling * 0.28F);
				legs[i][side].zRot -= sign * Math.max(0.0F, step) * crawling * 0.2F;
			}
		}
		for (int side = 0; side < 2; side++) {
			float sign = side == 0 ? 1.0F : -1.0F;
			palps[side].yRot += sign * Mth.sin(phase * 1.3F + side) * 0.12F;
			palps[side].getChild(side == 0 ? "left_palp_tip" : "right_palp_tip").xRot += Mth.sin(phase * 1.6F + side) * 0.18F;
		}
	}
}
