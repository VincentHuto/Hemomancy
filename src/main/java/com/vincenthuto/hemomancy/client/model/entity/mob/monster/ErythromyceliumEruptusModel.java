package com.vincenthuto.hemomancy.client.model.entity.mob.monster;

import com.vincenthuto.hemomancy.Hemomancy;
import com.vincenthuto.hemomancy.common.entity.mob.monster.ErythromyceliumEruptusEntity;
import com.vincenthuto.hemomancy.common.util.HemoEasing;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.util.Mth;

/**
 * One pose for each state, all read from the entity: the corpse lying still with a twitch now and then, trembling as it
 * swells; the eruption, which jolts it, grows the fungus out, unfolds the legs and hoists the body off the ground; and
 * the standing growth, breathing or walking on diagonal pairs with the body swinging beneath it; and the lunge, which
 * crouches low with the mouth drawing back, throws everything forward in the air, and slumps on landing. The mesh's bind
 * pose is the standing growth, so everything here is an offset from it. The mesh is generated by
 * tools/model_export/eruptus.py.
 */
public final class ErythromyceliumEruptusModel extends HierarchicalModel<ErythromyceliumEruptusEntity> {
	public static final ModelLayerLocation LAYER_LOCATION = new ModelLayerLocation(Hemomancy.rloc("erythromycelium_eruptus"), "main");
	private static final float RAD = Mth.DEG_TO_RAD;

	/** Matches HOIST in the generator: how far the bind pose stands above a corpse on the ground. */
	private static final float HOIST = 25.0F;
	private static final float LIMB_HANG = 35.0F * RAD;
	/** A body on its back is 2 deep and its head 4, so both rest on the ground only when lifted this far. */
	private static final float CORPSE_REST = 2.0F;
	private static final float FLAP_OPEN = 42.5F * RAD;
	private static final float MOUTH_OPEN = 37.5F * RAD;
	private static final float JAW_OPEN = 27.5F * RAD;

	// Eruption beats, as fractions of its length.
	private static final float JOLT_END = 0.38F;
	private static final float JOLT_HEIGHT = 3.0F;
	private static final float UNFOLD_START = 0.15F, UNFOLD_END = 0.9F;
	private static final float HOIST_START = 0.38F;
	private static final float SETTLE_START = 0.85F;

	private static final int TWITCH_PERIOD = 110;
	private static final int TWITCH_TICKS = 8;
	private static final float STRIDE_RATE = 0.75F;
	private static final float DEATH_TICKS = 20.0F;
	private static final float LUNGE_CROUCH = 6.0F;
	private static final float LANDING_SINK = 3.0F;
	private static final float LUNGE_BLEND_TICKS = 4.0F;
	private static final float LUNGE_TOTAL = ErythromyceliumEruptusEntity.LUNGE_WINDUP_TICKS
			+ ErythromyceliumEruptusEntity.LUNGE_AIR_TICKS + ErythromyceliumEruptusEntity.LUNGE_RECOVER_TICKS;

	private final ModelPart root;
	private final ModelPart host;
	private final ModelPart hostHead;
	private final ModelPart hostLeftArm;
	private final ModelPart hostRightArm;
	private final ModelPart hostLeftLeg;
	private final ModelPart hostRightLeg;
	private final ModelPart growth;
	private final ModelPart stalk;
	private final ModelPart cap;
	private final ModelPart mouth;
	private final ModelPart jaw;
	private final ModelPart[] leftFlaps;
	private final ModelPart[] rightFlaps;
	private final Leg leftFront;
	private final Leg rightFront;
	private final Leg leftHind;
	private final Leg rightHind;

	/** One leg, with the rotations that take it from the stance back to folded against the growth. */
	private record Leg(ModelPart hip, ModelPart knee, ModelPart shin, ModelPart tip, float sign, float pitch, float yaw) {
		private static final float FOLD_ROLL = 6.0F * RAD, FOLD_KNEE = 37.5F * RAD, FOLD_SHIN = 20.5F * RAD, FOLD_TIP = 128.0F * RAD;

		static Leg of(ModelPart growth, String prefix, float sign, float pitch, float yaw) {
			ModelPart hip = growth.getChild(prefix + "_hip");
			ModelPart knee = hip.getChild(prefix + "_knee");
			ModelPart shin = knee.getChild(prefix + "_shin");
			return new Leg(hip, knee, shin, shin.getChild(prefix + "_tip"), sign, pitch * RAD, yaw * RAD);
		}

		void fold(float amount) {
			hip.xRot -= pitch * amount;
			hip.yRot -= sign * yaw * amount;
			hip.zRot += sign * FOLD_ROLL * amount;
			knee.zRot += sign * FOLD_KNEE * amount;
			shin.zRot += sign * FOLD_SHIN * amount;
			tip.zRot += sign * FOLD_TIP * amount;
		}

		void stride(float phase, float amount) {
			hip.yRot += sign * Mth.cos(phase) * 0.42F * amount;
			float lift = Math.max(0.0F, Mth.sin(phase)) * amount;
			hip.zRot -= sign * lift * 0.34F;
			shin.zRot -= sign * lift * 0.22F;
		}

		/** Bends at the knee as the body sinks, so the foot stays near where it stands. */
		void flex(float amount) {
			hip.zRot -= sign * amount * 0.05F;
			knee.zRot += sign * amount * 0.1F;
		}

		/** Knees up and body down, feet about where they stood. */
		void crouch(float amount) {
			hip.zRot -= sign * amount * 0.5F;
			knee.zRot += sign * amount * 0.8F;
		}

		/** Thrown out flat in the air, ready to take the landing. */
		void spread(float amount) {
			hip.zRot -= sign * amount * 0.45F;
			shin.zRot -= sign * amount * 0.5F;
			tip.zRot -= sign * amount * 0.4F;
		}

		void curl(float amount) {
			knee.zRot += sign * amount * 0.7F;
			shin.zRot += sign * amount * 0.9F;
			tip.zRot += sign * amount * 0.9F;
		}
	}

	public ErythromyceliumEruptusModel(ModelPart bakedRoot) {
		root = bakedRoot.getChild("root");
		host = root.getChild("host");
		hostHead = host.getChild("host_head");
		hostLeftArm = host.getChild("host_left_arm");
		hostRightArm = host.getChild("host_right_arm");
		hostLeftLeg = host.getChild("host_left_leg");
		hostRightLeg = host.getChild("host_right_leg");
		growth = root.getChild("growth");
		stalk = growth.getChild("stalk");
		cap = stalk.getChild("cap");
		mouth = growth.getChild("mouth");
		jaw = mouth.getChild("jaw");
		leftFlaps = new ModelPart[3];
		rightFlaps = new ModelPart[3];
		for (int i = 0; i < 3; i++) {
			ModelPart skirt = stalk.getChild("skirt_" + i);
			leftFlaps[i] = skirt.getChild("skirt_" + i + "_left");
			rightFlaps[i] = skirt.getChild("skirt_" + i + "_right");
		}
		leftFront = Leg.of(growth, "left_front", 1.0F, -18.0F, 27.0F);
		rightFront = Leg.of(growth, "right_front", -1.0F, -18.0F, 27.0F);
		leftHind = Leg.of(growth, "left_hind", 1.0F, 18.0F, -27.0F);
		rightHind = Leg.of(growth, "right_hind", -1.0F, 18.0F, -27.0F);
	}

	public static LayerDefinition createBodyLayer() {
		return ErythromyceliumEruptusMesh.createBodyLayer();
	}

	@Override
	public ModelPart root() {
		return root;
	}

	@Override
	public void setupAnim(ErythromyceliumEruptusEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
		root.getAllParts().forEach(ModelPart::resetPose);
		float partialTick = ageInTicks - entity.tickCount;
		float eruption = entity.eruption(partialTick);
		// The renderer's death tilt is for a standing mob; the growth curls up instead.
		float dying = HemoEasing.clamp01((entity.deathTime + partialTick) / DEATH_TICKS);
		if (entity.deathTime == 0) dying = 0.0F;

		growth.visible = entity.isErupted();
		liftOffGround(eruption);
		if (eruption < 1.0F) corpseStirs(entity, entity.getSwelling(partialTick), ageInTicks, eruption);
		if (entity.isErupted()) {
			unfold(eruption);
			float settled = HemoEasing.smoothstep(SETTLE_START, 1.0F, eruption);
			breathe(ageInTicks, settled);
			float lungeAge = entity.lungeAge(partialTick);
			float lunging = lungeAge < 0.0F ? 0.0F : HemoEasing.clamp01(Math.min(lungeAge, LUNGE_TOTAL - lungeAge) / LUNGE_BLEND_TICKS);
			walk(limbSwing, Math.min(limbSwingAmount, 1.0F) * settled * (1.0F - lunging));
			if (lungeAge >= 0.0F) lunge(lungeAge);
			curlUp(dying);
		}
	}

	/** The jolt as it bursts, then the climb. At 0 this is the corpse on the ground. */
	private void liftOffGround(float eruption) {
		float hoist = HemoEasing.smoothstep(HOIST_START, 1.0F, eruption);
		float jolt = Mth.sin(HemoEasing.clamp01(eruption / JOLT_END) * Mth.PI) * JOLT_HEIGHT;
		root.y += HOIST * (1.0F - hoist) - jolt;
		host.y -= CORPSE_REST * (1.0F - hoist);
		hostHead.z -= CORPSE_REST * (1.0F - hoist);

		float hang = (1.0F - hoist) * LIMB_HANG;
		hostLeftArm.xRot -= hang;
		hostRightArm.xRot -= hang;
		hostLeftLeg.xRot -= hang;
		hostRightLeg.xRot -= hang;
	}

	/** Mostly still, as a body should be, until it swells; the eruption wrenches the limbs and head outward. */
	private void corpseStirs(ErythromyceliumEruptusEntity entity, float swelling, float age, float eruption) {
		int clock = (entity.tickCount + entity.getId() * 37) % TWITCH_PERIOD;
		float twitch = eruption > 0.0F || clock >= TWITCH_TICKS ? 0.0F : Mth.sin(clock / (float) TWITCH_TICKS * Mth.PI) * 0.28F;
		float tremble = Mth.sin(age * 2.4F) * swelling * 0.09F;
		float wrench = Mth.sin(HemoEasing.clamp01(eruption / JOLT_END) * Mth.PI);

		hostLeftArm.zRot -= twitch + tremble + wrench * 0.7F;
		hostRightArm.zRot += tremble + wrench * 0.7F;
		hostLeftLeg.zRot -= tremble * 0.6F + wrench * 0.35F;
		hostRightLeg.zRot += tremble * 0.6F + wrench * 0.35F;
		hostHead.xRot += tremble * 0.5F - wrench * 0.6F;
	}

	private void unfold(float eruption) {
		float size = HemoEasing.easeOutCubic(eruption);
		growth.xScale = size;
		growth.yScale = size;
		growth.zScale = size;

		float folded = 1.0F - HemoEasing.smoothstep(UNFOLD_START, UNFOLD_END, eruption);
		leftFront.fold(folded);
		rightFront.fold(folded);
		leftHind.fold(folded);
		rightHind.fold(folded);
		mouth.xRot += MOUTH_OPEN * folded;
		jaw.xRot += JAW_OPEN * folded;
		for (int i = 0; i < 3; i++) {
			leftFlaps[i].yRot += FLAP_OPEN * folded;
			rightFlaps[i].yRot -= FLAP_OPEN * folded;
		}
	}

	private void breathe(float age, float amount) {
		float breath = Mth.sin(age * 0.09F) * amount;
		root.y += breath * 0.7F;
		leftFront.flex(breath);
		rightFront.flex(breath);
		leftHind.flex(breath);
		rightHind.flex(breath);

		cap.xScale += breath * 0.04F;
		cap.yScale += breath * 0.04F;
		cap.zScale += breath * 0.04F;

		float sway = Mth.sin(age * 0.06F) * amount;
		host.xRot += sway * 0.04F;
		hostLeftArm.xRot += sway * 0.08F;
		hostRightArm.xRot -= sway * 0.08F;
		jaw.zRot += Mth.sin(age * 0.07F + 1.0F) * 0.12F * amount;
		for (int i = 0; i < 3; i++) {
			float flap = Mth.sin(age * 0.08F + i) * 0.09F * amount;
			leftFlaps[i].yRot += flap;
			rightFlaps[i].yRot -= flap;
		}
	}

	private void walk(float limbSwing, float amount) {
		if (amount <= 0.0F) return;
		float phase = limbSwing * STRIDE_RATE;
		leftFront.stride(phase, amount);
		rightHind.stride(phase, amount);
		rightFront.stride(phase + Mth.PI, amount);
		leftHind.stride(phase + Mth.PI, amount);

		// Two beats of the body for each stride, and the slung host swinging a little behind them.
		root.y -= Math.abs(Mth.sin(phase)) * 0.9F * amount;
		stalk.zRot += Mth.cos(phase) * 0.05F * amount;
		host.xRot += Mth.sin(phase * 2.0F - 0.7F) * 0.05F * amount;
		host.zRot += Mth.cos(phase - 0.7F) * 0.07F * amount;
		float limbs = Mth.sin(phase - 1.0F) * 0.22F * amount;
		hostLeftArm.xRot += limbs;
		hostRightArm.xRot -= limbs;
		hostLeftLeg.xRot -= limbs;
		hostRightLeg.xRot += limbs;
		jaw.zRot += Mth.cos(phase - 1.0F) * 0.18F * amount;
	}

	private void lunge(float age) {
		float airborneAt = ErythromyceliumEruptusEntity.LUNGE_WINDUP_TICKS;
		float landsAt = airborneAt + ErythromyceliumEruptusEntity.LUNGE_AIR_TICKS;
		float crouch = HemoEasing.smoothstep(age / airborneAt) * (1.0F - HemoEasing.smoothstep(airborneAt, airborneAt + 2.0F, age));
		float flight = HemoEasing.smoothstep(airborneAt, airborneAt + 3.0F, age) * (1.0F - HemoEasing.smoothstep(landsAt - 1.0F, landsAt + 1.0F, age));
		float slump = HemoEasing.smoothstep(landsAt - 1.0F, landsAt + 1.0F, age) * (1.0F - HemoEasing.smoothstep(landsAt + 2.0F, LUNGE_TOTAL, age));

		float legsDown = crouch + slump * 0.55F;
		leftFront.crouch(legsDown);
		rightFront.crouch(legsDown);
		leftHind.crouch(legsDown);
		rightHind.crouch(legsDown);
		leftFront.spread(flight);
		rightFront.spread(flight);
		leftHind.spread(flight);
		rightHind.spread(flight);
		root.y += crouch * LUNGE_CROUCH + slump * LANDING_SINK;
		root.xRot += flight * 0.3F + slump * 0.12F - crouch * 0.1F;

		// Reared back over the crouch, then the cap and the open mouth lead the leap.
		stalk.xRot += flight * 0.45F - crouch * 0.35F + slump * 0.3F;
		mouth.xRot += crouch * 0.4F - flight * 0.75F;
		jaw.xRot += crouch * 0.2F - flight * 0.65F;
		float limbs = flight * 0.5F;
		hostLeftArm.xRot += limbs;
		hostRightArm.xRot += limbs;
		hostLeftLeg.xRot += limbs;
		hostRightLeg.xRot += limbs;
		for (int i = 0; i < 3; i++) {
			leftFlaps[i].yRot += flight * 0.3F - crouch * 0.2F;
			rightFlaps[i].yRot -= flight * 0.3F - crouch * 0.2F;
		}
	}

	private void curlUp(float dying) {
		if (dying <= 0.0F) return;
		leftFront.curl(dying);
		rightFront.curl(dying);
		leftHind.curl(dying);
		rightHind.curl(dying);
		root.y += dying * HOIST * 0.8F;
	}
}
