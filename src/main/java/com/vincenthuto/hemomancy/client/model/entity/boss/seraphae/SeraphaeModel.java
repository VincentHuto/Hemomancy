	@Override
	public void setupAnim(T entity, float limbSwing, float limbSwingAmount, float ageInTicks,
			float netHeadYaw, float headPitch) {
		float partial = AnimationTime.partialTick();
		SeraphaeAnimState state = SeraphaeAnimState.of(entity);
		state.update(entity, partial, ageInTicks);
		select(entity, state, partial);
		float[] a = target.zero().channels();
		boolean still = state.track() == SeraphaeAnimState.TRACK_ENDING;
		float calm = still ? 1.0F - HemoEasing.smoothstep(40.0F, 75.0F, state.time()) : 1.0F;
		stance(a, state.reaching(), state.restraint(), state.escaping(), state.breath(), ageInTicks,
				(1.0F - state.busy()) * calm, entity.syncedRestraints(), entity.getId(), calm);
		drift(a, state.forward(), state.side(), state.turn(), state.strain(), state.reeled(), state.busy(), ageInTicks);
		track(a, state);
		if (state.cardPhase() != 0) card(a, state.cardPhase(), state.cardTime());
		state.blend(a, ageInTicks);
		secondary(a, state);
		float gaze = (1.0F - state.busy() * 0.5F) * calm;
		pose(a, ageInTicks, netHeadYaw * gaze, headPitch * gaze, entity.syncedRestraints(), entity.getId());
	}

	/**
	 * Picks the playing track from the kit's synced state, each read through the move view's replay clocks: the ending,
	 * the rise, a move on its authored clock (its recovery gives way to the hold or to the opening it opened, except the
	 * Eye, whose own track carries its Lapse), the hold, an opening, or the idle.
	 */
	private static void select(SeraphaeEntity entity, SeraphaeAnimState state, float partial) {
		var view = entity.view();
		float ending = view.endingTime(partial);
		if (ending >= 0.0F) {
			state.play(SeraphaeAnimState.TRACK_ENDING, ending, 0);
			return;
		}
		float rise = entity.riseTime(partial);
		if (rise >= 0.0F && rise < SaintRise.TICKS) {
			state.play(SeraphaeAnimState.TRACK_RISE, rise, 0);
			return;
		}
		SeraphaeMove move = SeraphaeMove.byId(view.moveId());
		float moveTime = view.moveTime(partial);
		boolean held = entity.syncedHoldPlayer() >= 0;
		int opening = view.openingId();
		if (move != null && moveTime >= 0.0F) {
			SaintMoveInputs inputs = view.inputs();
			BossMoveTimeline timeline = move.timeline(inputs);
			BossMoveTimeline base = move.timeline(new SaintMoveInputs(inputs.phase(),
					inputs.variant() & ~SeraphaeMove.HASTY, 0, inputs.challengers()));
			boolean recovering = moveTime >= timeline.windup() + timeline.active();
			if (recovering && held && move.reach()) {
				state.play(SeraphaeAnimState.TRACK_HOLD, 0.0F, 0);
				return;
			}
			if (recovering && opening != 0 && move != SeraphaeMove.UNCLOSING_EYE) {
				state.play(SeraphaeAnimState.TRACK_OPENING + opening, Math.max(0.0F, view.openingTime(partial)), 0);
				return;
			}
			state.play(SeraphaeAnimState.TRACK_MOVE + move.id(), SeraphaeAnimState.authored(moveTime, timeline.windup(),
					timeline.active(), timeline.recovery(), base.windup(), base.recovery()), entity.syncedMoveSerial());
			return;
		}
		if (held) {
			state.play(SeraphaeAnimState.TRACK_HOLD, 0.0F, 0);
			return;
		}
		if (opening != 0) {
			state.play(SeraphaeAnimState.TRACK_OPENING + opening, Math.max(0.0F, view.openingTime(partial)), 0);
			return;
		}
		state.play(SeraphaeAnimState.TRACK_IDLE, 0.0F, 0);
	}

	/** The playing track's deltas at its time, over the idle and the glide. */
	static void track(float[] a, SeraphaeAnimState state) {
		int track = state.track();
		float t = state.time();
		if (track == SeraphaeAnimState.TRACK_ENDING) ending(a, t);
		else if (track == SeraphaeAnimState.TRACK_RISE) rise(a, t);
		else if (track == SeraphaeAnimState.TRACK_HOLD) hold(a, t);
		else if (track > SeraphaeAnimState.TRACK_OPENING) opening(a, track - SeraphaeAnimState.TRACK_OPENING, t,
				state.openingLength(), state.seized());
		else if (track > SeraphaeAnimState.TRACK_MOVE) move(a, SeraphaeMove.byId(track - SeraphaeAnimState.TRACK_MOVE), t,
				state.variant(), state.aim());
	}

	private static float win(float t, float a, float b, float c, float d) {
		return HemoEasing.window(t, a, b, c, d);
	}

	/** A one-shot beat at {@code at}: up over {@code attack} ticks, gone by {@code length}. */
	private static float beat(float t, float at, float attack, float length) {
		return HemoEasing.pulse(t - at, attack, length);
	}

