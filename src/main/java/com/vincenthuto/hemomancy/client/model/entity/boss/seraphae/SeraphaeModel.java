	// ── the idle: her phase and her irons ────────────────────────────

	/**
	 * Her body at rest by phase, as smooth weights so the idle never steps. The Reaching: tender, palms half-open and
	 * turned up before her, the head tilted, and every so often one hand drifts out toward whoever is hurt (the old
	 * instinct). The Restraint: drawn back by the chains, hands half-closed, the wrists turning in their irons, and
	 * now and then a tug against a chain that is stopped short. The Escaping Light: chest open, head back, arms lowered
	 * from her sides with the fingers splayed, wings raised and fanned, a constant fine tremble. Under all of it the
	 * hover's float and the breath; a slipped iron lets that limb hang freer, a slipped wing droops. {@code fidget}
	 * fades the gestures under a move, {@code calm} stills everything in the ending.
	 */
	static void stance(float[] a, float reaching, float restraint, float escaping, float breath, float age, float fidget,
			int restraints, int seed, float calm) {
		float inhale = Mth.sin(breath);
		float depth = (0.03F * reaching + 0.04F * restraint + 0.07F * escaping) * calm;
		a[LIFT] += (Mth.sin(breath * 0.5F + 0.6F) * 0.55F + inhale * 0.15F) * calm;
		a[ARCH] += inhale * depth;
		a[HEAD_PITCH] -= inhale * depth * 0.4F;
		arms(a, A_OUT, inhale * depth * 0.5F);
		// the Reaching: an offering, palms up before her
		arms(a, A_RAISE, 0.28F * reaching);
		arms(a, A_OUT, -0.08F * reaching);
		arms(a, A_FORE, 0.5F * reaching);
		arms(a, A_WRIST, -0.22F * reaching);
		arms(a, A_HAND, 0.35F * reaching);
		arms(a, A_TWIST, 0.4F * reaching);
		a[HEAD_TILT] += 0.12F * reaching;
		a[HEAD_PITCH] += 0.08F * reaching;
		wings(a, W_SPREAD, 0.1F * reaching);
		// one hand drifts out toward the hurt, then withdraws; the hands take turns
		float drift = SeraphaeHover.every(age, 96.0F, seed % 50, 0.0F, 14.0F, 28.0F, 46.0F) * reaching * fidget;
		boolean leftHand = (SeraphaeHover.cycle(age, 96.0F, seed % 50) & 1) == 0;
		a[armCh(leftHand, A_RAISE)] += 0.45F * drift;
		a[armCh(leftHand, A_FORE)] -= 0.35F * drift;
		a[armCh(leftHand, A_HAND)] += 0.5F * drift;
		a[armCh(leftHand, A_WRIST)] -= 0.2F * drift;
		a[HEAD_TURN] += (leftHand ? -0.1F : 0.1F) * drift;
		a[LEAN] += 0.04F * drift;
		// the Restraint: drawn back by her chains, wrists turning in the iron, a tug stopped short
		arms(a, A_RAISE, -0.12F * restraint);
		arms(a, A_OUT, 0.15F * restraint);
		arms(a, A_FORE, 0.25F * restraint);
		arms(a, A_HAND, -0.2F * restraint);
		a[ARM_L_TWIST] += Mth.sin(age * 0.05F) * 0.25F * restraint * fidget;
		a[ARM_R_TWIST] += Mth.sin(age * 0.05F + 2.1F) * 0.25F * restraint * fidget;
		a[HEAD_PITCH] += 0.14F * restraint;
		a[LEAN] += 0.05F * restraint;
		allTrunks(a, TRUNK_CURL, 0.12F * restraint);
		int tug = SeraphaeHover.cycle(age, 80.0F, seed % 37);
		float into = age + seed % 37 - tug * 80.0F;
		// a fast pull forward, stopped dead by the chain (the overshoot back), then let go
		float pull = catmullRom(into, 0, 0, 2.5F, 0.42F, 4.0F, 0.3F, 5.5F, 0.34F, 14, 0.25F, 24, 0) * restraint * fidget;
		boolean tugLeft = (tug & 1) == 0;
		a[armCh(tugLeft, A_RAISE)] += pull;
		a[armCh(tugLeft, A_HAND)] -= pull * 1.2F;
		a[TWIST] += (tugLeft ? 0.12F : -0.12F) * pull;
		a[HEAD_TURN] += (tugLeft ? -0.35F : 0.35F) * pull;
		a[HEAD_PITCH] += 0.25F * pull;
		// the Escaping Light: chest open, arms lowered from her sides, fingers splayed, wings raised and fanned
		a[ARCH] += 0.18F * escaping;
		a[HEAD_PITCH] -= 0.12F * escaping;
		arms(a, A_OUT, 0.42F * escaping);
		arms(a, A_RAISE, 0.12F * escaping);
		arms(a, A_TWIST, -0.5F * escaping);
		arms(a, A_HAND, 0.8F * escaping);
		wings(a, W_SPREAD, 0.45F * escaping);
		wings(a, W_RAISE, 0.2F * escaping);
		wings(a, W_TIPS, 0.5F * escaping);
		a[TREMOR] += 0.12F * escaping * calm;
		// her irons: a slipped wrist hangs freer of the pull back, a slipped wing droops and swings out
		for (SeraphaeRestraint iron : SeraphaeRestraint.BINDING) {
			if (!slipped(restraints, iron)) continue;
			if (iron.wing()) {
				a[wingCh(iron.left(), W_RAISE)] -= 0.3F;
				a[wingCh(iron.left(), W_SWEEP)] += 0.15F;
				trunks(a, TRUNK_CURL, iron.left(), 0.2F);
			} else {
				a[armCh(iron.left(), A_RAISE)] += 0.12F * restraint + 0.05F;
				a[armCh(iron.left(), A_OUT)] += 0.08F;
			}
		}
	}

	// ── the glide ────────────────────────────────────────────────────

	/**
	 * Her locomotion over the idle, from her real motion: she leans into the glide (eight degrees at full speed) and
	 * banks into a slide, her wings draw back and her feet trail; stopping short she rocks past upright and settles (the
	 * smoothing spring is a little under-damped). At her chain's end she strains: leaning at the target, arms dragged
	 * back by their chains, wings straining forward against their roots, heaving every so often. Reeled, she arches back
	 * with her hands pulled toward their anchors and her wings flattened. Turning, her chest and head lead.
	 */
	static void drift(float[] a, float forward, float side, float turn, float strain, float reeled, float busy, float age) {
		float glide = Math.max(-1.0F, Math.min(1.6F, forward));
		float free = 1.0F - busy * 0.5F;
		a[LEAN] += 0.14F * glide * free;
		a[SWAY] -= 0.1F * Math.max(-1.0F, Math.min(1.0F, side)) * free;
		wings(a, W_SWEEP, -0.26F * Math.abs(glide) * free);
		wings(a, W_RAISE, -0.06F * Math.abs(glide) * free);
		arms(a, A_RAISE, -0.12F * glide * free);
		a[TRAIL] += 0.55F * Math.max(0.0F, glide) * free;
		a[HEAD_PITCH] -= 0.05F * glide * free;
		// the strain at her chain's end, heaving against it every 24 ticks
		float heave = SeraphaeHover.every(age, 24.0F, 0.0F, 0.0F, 5.0F, 7.0F, 16.0F) * strain;
		a[LEAN] += 0.33F * strain + 0.07F * heave;
		a[HEAD_PITCH] -= 0.12F * strain;
		arms(a, A_RAISE, -0.55F * strain - 0.15F * heave);
		arms(a, A_OUT, 0.15F * strain);
		arms(a, A_HAND, 0.6F * strain);
		arms(a, A_WRIST, -0.3F * strain);
		wings(a, W_SWEEP, 0.45F * strain + 0.12F * heave);
		wings(a, W_RAISE, -0.1F * strain);
		allTrunks(a, TRUNK_CURL, -0.15F * strain);
		a[TREMOR] += 0.22F * strain + 0.15F * heave;
		a[TRAIL] += 0.3F * strain;
		// reeled back toward the dais
		a[ARCH] += 0.5F * reeled;
		a[HEAD_PITCH] += 0.35F * reeled;
		arms(a, A_RAISE, -0.9F * reeled);
		arms(a, A_OUT, 0.3F * reeled);
		arms(a, A_HAND, 0.5F * reeled);
		wings(a, W_FOLD, 0.45F * reeled);
		wings(a, W_SWEEP, -0.3F * reeled);
		a[TRAIL] -= 0.6F * reeled;
		a[TREMOR] += 0.15F * reeled;
		// the turn: chest and head lead, banking into it
		float into = Math.max(-1.0F, Math.min(1.0F, turn));
		a[TWIST] += 0.2F * into;
		a[HEAD_TURN] += 0.3F * into;
		a[SWAY] -= 0.05F * into;
	}

	// ── the moves ────────────────────────────────────────────────────

	/** A move's authored length: its base wind-up, active span and recovery, with no deed and the full wind-up. */
	static int length(SeraphaeMove move) {
		BossMoveTimeline timeline = move.timeline(new SaintMoveInputs(3, SeraphaeMove.laneVariant(6.0D, false), 0, 1));
		return timeline.windup() + timeline.active() + timeline.recovery();
	}

	/** For tests and the review: a move with no aim off her facing. */
	static void move(float[] a, SeraphaeMove move, float t, int variant) {
		move(a, move, t, variant, 0.0F);
	}

	/**
	 * Every move as deltas on its authored clock: each starts and ends at zero, so it rises out of the idle and settles
	 * back into it. The commit (the end of the authored wind-up) is where the strike's arc runs fastest. {@code aim} is
	 * where the move aims off her facing (radians, positive right): it chooses the reaching wing or hand and turns her.
	 */
	static void move(float[] a, SeraphaeMove move, float t, int variant, float aim) {
		if (move == null) return;
		switch (move) {
			case LAYING_ON_OF_HANDS -> reach(a, t, false, aim);
			case STRAINING_REACH -> reach(a, t, true, aim);
			case NERVE_LASH -> nerveLash(a, t, variant == 0);
			case COUNTER_LASH -> counterLash(a, t, variant == 0);
			case AXON_LANCE, AXON_MIRROR -> axonLance(a, t, variant == 0);
			case REGROWTH_KNOT -> regrowthKnot(a, t, aim);
			case TRANSFUSION_THREAD -> transfusionThread(a, t, aim);
			case WING_GRASP -> wingGrasp(a, t, aim);
			case CONVULSION -> convulsion(a, t, 22, 12, 1.0F);
			case CONVULSION_WIDE -> convulsion(a, t, 20, 14, -1.0F);
			case CHAIN_WRENCH -> chainWrench(a, t, aim);
			case FRACTURE -> fracture(a, t);
			case HEALED_GROUND -> healedGround(a, t, aim);
			case UNCLOSING_EYE -> unclosingEye(a, t, variant == 0);
			case EXTRACTION -> extraction(a, t);
			case RADIANCE_FLOOD -> radianceFlood(a, t);
		}
	}

	/**
	 * The Laying On of Hands, 24 / 10 / 20, and the Straining Reach, 28 / 14 / 24 (its first 12 ticks tear one chain
	 * loose). The palms turn out and rise to her chest as she draws herself up and back (the coil), wings drawn back,
	 * head lifting; at the commit she throws herself down the lane, body pitched forward, arms driven out, fingers
	 * spread, wings swept back behind her and the feet trailing; where she stops she rocks on past the line, the arms
	 * swinging up as the wings swing forward, and settles. A catch hands over to the hold.
	 */
	static void reach(float[] a, float t, boolean straining, float aim) {
		float s = straining ? 12.0F : 0.0F;
		float c = straining ? 28.0F : 24.0F;
		float e = c + (straining ? 14.0F : 10.0F);
		float end = straining ? 66.0F : 54.0F;
		float deep = straining ? 1.35F : 1.0F;
		// the wind-up's own beats, a third and two thirds of the way from its start to the commit
		float w1 = s + (c - s) * 0.33F, w2 = s + (c - s) * 0.66F, w3 = c - 2.0F;
		if (straining) {
			// the tear: one hand finds the chain on the target's side, coils, and wrenches it loose
			boolean left = aim < 0.0F;
			float toward = left ? -1.0F : 1.0F;
			a[TWIST] += toward * catmullRom(t, 0, 0, 4, 0.25F, 9, 0.42F, 11, -0.45F, 14, -0.32F, 20, 0, end, 0);
			a[armCh(left, A_RAISE)] += catmullRom(t, 0, 0, 4, -0.6F, 9, -0.78F, 11, 0.55F, 14, 0.45F, 20, 0, end, 0);
			a[armCh(left, A_OUT)] += catmullRom(t, 0, 0, 4, 0.35F, 9, 0.4F, 11, -0.1F, 16, 0, end, 0);
			a[armCh(left, A_HAND)] += catmullRom(t, 0, 0, 3, -0.9F, 10, -1.0F, 12, 0.5F, 16, 0, end, 0);
			a[LEAN] += catmullRom(t, 0, 0, 9, -0.16F, 11, 0.22F, 14, 0.1F, 18, 0, end, 0);
			a[JITTER] += beat(t, 10.5F, 0.6F, 5.0F) * 0.5F;
		}
		float lean = catmullRom(t, 0, 0, s + (c - s) * 0.4F, -0.06F * deep, c - 4, -0.13F * deep, c, -0.12F * deep,
				c + 3, 0.5F * deep, e - 3, 0.48F * deep, e, 0.46F * deep, e + 3, 0.6F * deep, e + 7, 0.33F, e + 14, 0.07F, end, 0);
		a[LEAN] += lean;
		a[ARCH] += catmullRom(t, 0, 0, s + (c - s) * 0.66F, 0.12F, c, 0.15F, c + 3, -0.05F, e, 0, end, 0);
		a[LIFT] += straining
				? catmullRom(t, 0, 0, 12, 0, 22, -1.6F, c, -1.5F, c + 3, -1.2F, e, -1.4F, e + 6, -1.0F, end, 0)
				: catmullRom(t, 0, 0, 16, 0.9F, c, 1.2F, c + 3, -0.4F, e, -0.6F, e + 6, -0.9F, end, 0);
		float raise = straining
				? catmullRom(t, 0, 0, 12, 0, 18, -0.3F, 24, 0.6F, c, 0.95F, c + 2.5F, 1.6F, e, 1.5F, e + 3, 1.68F, e + 10, 0.7F, e + 16, 0.15F, end, 0)
				: catmullRom(t, 0, 0, 8, 0.45F, 16, 0.95F, 22, 1.05F, c, 1.08F, c + 2.5F, 1.55F, e, 1.48F, e + 3, 1.62F, e + 10, 0.7F, e + 16, 0.15F, end, 0);
		arms(a, A_RAISE, raise);
		arms(a, A_OUT, catmullRom(t, 0, 0, w1, -0.05F, c, -0.12F, c + 3, -0.3F, e, -0.3F, e + 10, -0.1F, end, 0));
		arms(a, A_FORE, catmullRom(t, 0, 0, w1, 0.6F, w2, 0.85F, w3, 0.5F, c, 0.4F, c + 2.5F, 0.05F, e, 0.1F, e + 10, 0.3F, end, 0));
		arms(a, A_WRIST, catmullRom(t, 0, 0, w1 + 2, -0.5F, w2, -0.9F, c, -0.95F, c + 3, -0.7F, e, -0.75F, e + 10, -0.3F, end, 0));
		arms(a, A_TWIST, catmullRom(t, 0, 0, w2 - 4, 0.5F, c, 0.6F, e, 0.6F, end - 4, 0, end, 0));
		arms(a, A_HAND, catmullRom(t, 0, 0, w2 - 4, 0.3F, w3 - 4, 0.7F, c, 1.0F, c + 3, 1.25F, e, 1.0F, e + 6, 0.6F, end, 0));
		a[HEAD_PITCH] += catmullRom(t, 0, 0, w2, -0.22F, c, -0.25F, c + 3, 0.05F, e, 0.1F, e + 10, 0.05F, end, 0);
		wings(a, W_SWEEP, catmullRom(t, 0, 0, w2, -0.45F, c, -0.6F, c + 3, -1.0F, e - 1, -0.95F, e + 3, -0.2F, e + 8, 0.25F, end - 6, 0.05F, end, 0));
		wings(a, W_RAISE, catmullRom(t, 0, 0, w2, 0.2F, c, 0.3F, c + 3, -0.1F, e, -0.15F, end, 0));
		wings(a, W_TIPS, catmullRom(t, 0, 0, c, 0.3F, c + 3, -0.4F, e, -0.3F, e + 6, 0.4F, end, 0));
		allTrunks(a, TRUNK_CURL, catmullRom(t, 0, 0, c, 0.1F, c + 3, -0.4F, e, -0.3F, e + 6, 0.3F, e + 14, 0, end, 0));
		a[TRAIL] += catmullRom(t, 0, 0, c, 0.1F, c + 3, 0.8F * deep, e, 0.7F * deep, e + 6, 0.1F, end, 0);
		a[TREMOR] += catmullRom(t, 0, 0, c - 6, 0, c - 2, 0.2F, c, 0.25F, c + 1, 0, end, 0);
	}

	/**
	 * The hold: the catch (hands closing on the patient's shoulders and chest, she bends in and sinks to them, head
	 * tilted, wings sweeping forward and curling round them), then a slow rocking 40-tick cycle with a squeeze through
	 * hands and wings every ten ticks as the transfusion runs, growing more urgent the longer she holds. {@code h} is
	 * ticks since this client saw the hold begin.
	 */
	static void hold(float[] a, float h) {
		float c = catmullRom(h, 0, 0, 3, 1.1F, 6, 1.0F, 8, 1.0F);
		float rock = Mth.sin(h * Mth.TWO_PI / 40.0F);
		float urgent = HemoEasing.smoothstep(20.0F, 55.0F, h);
		float squeeze = HemoEasing.pulse(h - (float) Math.floor(h / 10.0F) * 10.0F, 1.2F, 7.0F) * (0.6F + 0.6F * urgent)
				* HemoEasing.ramp(h, 4.0F, 8.0F);
		a[LEAN] += 0.48F * c + 0.05F * rock + 0.03F * squeeze;
		a[SWAY] += 0.04F * Mth.sin(h * Mth.TWO_PI / 40.0F + 1.2F);
		a[LIFT] += -2.0F * c + 0.3F * rock;
		a[HEAD_PITCH] += 0.35F * c;
		a[HEAD_TILT] += 0.25F * c;
		a[ARCH] += 0.04F * squeeze;
		arms(a, A_RAISE, 0.85F * c);
		arms(a, A_OUT, -0.15F * c);
		arms(a, A_FORE, 0.75F * c);
		arms(a, A_WRIST, 0.2F * c);
		arms(a, A_TWIST, 0.2F * c);
		arms(a, A_HAND, catmullRom(h, 0, 0.8F, 2, -0.9F, 5, -0.7F, 8, -0.7F) - 0.3F * squeeze);
		wings(a, W_SWEEP, 1.15F * c);
		wings(a, W_RAISE, -0.15F * c);
		wings(a, W_SPREAD, -0.2F * c);
		wings(a, W_TIPS, catmullRom(h, 0, 0, 4, -0.6F, 8, -0.6F) - 0.25F * squeeze + 0.1F * rock);
		allTrunks(a, TRUNK_CURL, 0.7F * c + 0.12F * squeeze);
		a[TREMOR] += 0.15F * urgent;
	}

	/**
	 * Nerve Lash, 14 / 6 / 16, on the wing nearer the target ({@code left} for variant 0). She dips and turns away,
	 * the wing's lower trunk dropping low and drawing back with its segments arched behind; at the commit her whole body
	 * turns into the whip, the trunk cracks forward low across the front and its tip snaps on past the line, then it
	 * recoils and settles. The other arm flings out to balance her; her head stays on the target.
	 */
	static void nerveLash(float[] a, float t, boolean left) {
		float m = left ? 1.0F : -1.0F;
		float turn = m * catmullRom(t, 0, 0, 6, -0.2F, 12, -0.42F, 14, -0.45F, 16, 0.05F, 18, 0.65F, 20, 0.85F, 23, 0.7F,
				28, 0.25F, 33, 0.05F, 36, 0);
		a[TURN] += turn;
		a[HEAD_TURN] -= turn * 0.6F;
		int lower = trunkCh(left, 2);
		float sweep = catmullRom(t, 0, 0, 6, -0.5F, 12, -0.85F, 14, -0.9F, 15.5F, 0.3F, 17, 1.25F, 19, 1.45F, 21, 1.0F, 26, 0.35F,
				31, 0.05F, 36, 0);
		a[TRUNK_SWEEP + lower] += sweep;
		a[TRUNK_RAISE + lower] += catmullRom(t, 0, 0, 8, -0.45F, 14, -0.55F, 17, -0.35F, 20, -0.25F, 28, -0.05F, 36, 0);
		a[TRUNK_CURL + lower] += catmullRom(t, 0, 0, 8, -0.4F, 14, -0.5F, 15.5F, -0.6F, 17, 0.3F, 19, 0.9F, 22, 0.5F, 28, 0.1F, 36, 0);
		for (int place = 0; place < 2; place++) {
			int other = trunkCh(left, place);
			a[TRUNK_SWEEP + other] += catmullRom(t - 1.0F - place, 0, 0, 6, -0.5F, 12, -0.85F, 14, -0.9F, 15.5F, 0.3F, 17, 1.25F,
					19, 1.45F, 21, 1.0F, 26, 0.3F, 30, 0, 34, 0) * 0.45F;
			a[TRUNK_CURL + other] += catmullRom(t, 0, 0, 10, -0.2F, 15, -0.25F, 19, 0.3F, 30, 0, 36, 0);
		}
		a[wingCh(left, W_SWEEP)] += catmullRom(t, 0, 0, 8, -0.3F, 14, -0.4F, 16, 0.2F, 19, 0.55F, 24, 0.25F, 36, 0);
		a[wingCh(left, W_RAISE)] += catmullRom(t, 0, 0, 8, -0.25F, 14, -0.3F, 18, -0.15F, 36, 0);
		a[wingCh(left, W_TIPS)] += catmullRom(t, 0, 0, 12, -0.4F, 15, -0.6F, 18, 1.0F, 22, 0.6F, 36, 0);
		a[wingCh(!left, W_SWEEP)] += catmullRom(t, 0, 0, 14, 0.1F, 18, -0.25F, 26, -0.05F, 36, 0);
		a[LEAN] += catmullRom(t, 0, 0, 10, -0.05F, 14, -0.08F, 17, 0.18F, 20, 0.2F, 28, 0.05F, 36, 0);
		a[SWAY] += m * catmullRom(t, 0, 0, 12, 0.08F, 14, 0.09F, 17, -0.08F, 20, -0.1F, 28, -0.02F, 36, 0);
		a[LIFT] += catmullRom(t, 0, 0, 12, -0.6F, 14, -0.7F, 18, -0.2F, 26, 0.2F, 36, 0);
		a[armCh(left, A_RAISE)] += catmullRom(t, 0, 0, 14, -0.35F, 18, 0.25F, 26, 0.05F, 36, 0);
		a[armCh(!left, A_OUT)] += catmullRom(t, 0, 0, 14, 0.1F, 18, 0.45F, 24, 0.3F, 36, 0);
		a[armCh(!left, A_HAND)] += catmullRom(t, 0, 0, 14, 0, 18, 0.6F, 28, 0.1F, 36, 0);
	}

	/**
	 * Counter-Lash, 12 / 6 / 22, on the other wing. It rises high and arches over her head toward her far side, the
	 * trunks bowed back, as she rises and leans away; at the commit it whips down and across in front of her with her
	 * whole body turning and bowing into it, the tips cracking open past the line, then it swings back and settles.
	 */
