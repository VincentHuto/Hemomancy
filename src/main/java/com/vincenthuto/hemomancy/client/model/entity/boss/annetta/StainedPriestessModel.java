	/** Places the lancea and solves both arms onto its shaft; an empty hand keeps its authored pose. */
	private void holdSpear(Grip grip) {
		Quaternionf chain = new Quaternionf()
				.mul(new Quaternionf().rotationZYX(this.hips.zRot, this.hips.yRot, this.hips.xRot))
				.mul(new Quaternionf().rotationZYX(this.torso.zRot, this.torso.yRot, this.torso.xRot))
				.mul(new Quaternionf().rotationZYX(this.chest.zRot, this.chest.yRot, this.chest.xRot))
				.mul(new Quaternionf().rotationZYX(this.body.zRot, this.body.yRot, this.body.xRot));
		Quaternionf aim = new Quaternionf().rotateY(-grip.yaw()).rotateX(-grip.pitch());
		Quaternionf local = chain.conjugate().mul(aim);
		// Through a matrix: JOML 1.10.5's Quaternionf.getEulerAnglesZYX returns a wrong X angle.
		Vector3f euler = new Matrix3f().set(local).getEulerAnglesZYX(new Vector3f());
		this.spear.x = grip.x();
		this.spear.y = grip.y();
		this.spear.z = grip.z();
		this.spear.xRot = euler.x;
		this.spear.yRot = euler.y;
		this.spear.zRot = euler.z;
		float hold = Mth.clamp(this.spearShown * 1.6F, 0.0F, 1.0F);
		reach(this.rightArm, this.rightForearm, grip.x(), grip.y(), grip.z(), -0.8F, 0.5F, 1.0F, hold);
		if (grip.left() > 0.0F) {
			Vector3f along = local.transform(new Vector3f(0.0F, 0.0F, grip.along()));
			reach(this.leftArm, this.leftForearm, grip.x() + along.x, grip.y() + along.y, grip.z() + along.z,
					0.8F, 0.5F, 1.0F, grip.left() * hold);
		}
	}

	/**
	 * Two-bone reach in body space: the upper arm turns so the hand lands on the target with the elbow bent toward
	 * the pole, and the forearm hinges about its own X. Blends from the authored pose by {@code weight}.
	 */
	private static void reach(ModelPart upper, ModelPart fore, float tx, float ty, float tz, float poleX, float poleY,
			float poleZ, float weight) {
		if (weight <= 0.0F) return;
		Vector3f dir = new Vector3f(tx - upper.x, ty - upper.y, tz - upper.z);
		float distance = dir.length();
		if (distance < 1.0E-3F) return;
		dir.div(distance);
		float span = Mth.clamp(distance, Math.abs(UPPER_ARM - FOREARM) + 0.3F, UPPER_ARM + FOREARM - 0.05F);
		float cos = (UPPER_ARM * UPPER_ARM + span * span - FOREARM * FOREARM) / (2.0F * UPPER_ARM * span);
		float angle = (float) Math.acos(Mth.clamp(cos, -1.0F, 1.0F));
		Vector3f bend = new Vector3f(poleX, poleY, poleZ);
		bend.sub(new Vector3f(dir).mul(bend.dot(dir)));
		if (bend.lengthSquared() < 1.0E-6F) bend.set(0.0F, 0.0F, 1.0F).sub(new Vector3f(dir).mul(dir.z));
		bend.normalize();
		Vector3f upperDir = new Vector3f(dir).mul(Mth.cos(angle)).add(new Vector3f(bend).mul(Mth.sin(angle)));
		Vector3f foreDir = new Vector3f(dir).mul(span).sub(new Vector3f(upperDir).mul(UPPER_ARM)).normalize();
		Vector3f hinge = new Vector3f(upperDir).cross(foreDir);
		if (hinge.lengthSquared() < 1.0E-6F) hinge.set(upperDir).cross(bend);
		hinge.normalize();
		Vector3f front = new Vector3f(hinge).cross(upperDir);
		// Elbows only flex one way: keep the forearm swinging toward the arm's front.
		if (foreDir.dot(front) > 0.0F) {
			hinge.negate();
			front.negate();
		}
		Vector3f euler = new Matrix3f(hinge.x, hinge.y, hinge.z, upperDir.x, upperDir.y, upperDir.z, front.x, front.y, front.z)
				.getEulerAnglesZYX(new Vector3f());
		float elbow = (float) Math.atan2(foreDir.dot(front), foreDir.dot(upperDir));
		upper.xRot = wrapLerp(weight, upper.xRot, euler.x);
		upper.yRot = wrapLerp(weight, upper.yRot, euler.y);
		upper.zRot = wrapLerp(weight, upper.zRot, euler.z);
		fore.xRot = Mth.lerp(weight, fore.xRot, elbow);
	}

	/** Robe tatters swing with the leg behind them and drag in the air. */
	private void swayTatters(float amount, float ageInTicks) {
		ModelPart[] front = {this.robeTatters0, this.robeTatters1, this.robeTatters2};
		ModelPart[] back = {this.robeTatters3, this.robeTatters4};
		for (ModelPart tatter : front) {
			ModelPart leg = tatter.x < 0.0F ? this.rightLeg : this.leftLeg;
			tatter.xRot = Math.min(0.0F, leg.xRot) * 0.85F - 0.05F + Mth.sin(ageInTicks * 0.1F + tatter.x) * 0.05F;
		}
		for (ModelPart tatter : back) {
			ModelPart leg = tatter.x < 0.0F ? this.rightLeg : this.leftLeg;
			tatter.xRot = Math.max(0.0F, leg.xRot) * 0.85F + 0.05F + Math.min(1.0F, amount) * 0.25F
					+ Mth.sin(ageInTicks * 0.1F + tatter.x) * 0.05F;
		}
		// Tatters hang from the hips; undo the hips' lean so they fall toward the floor.
		for (ModelPart tatter : front) tatter.xRot -= this.hips.xRot * 0.7F;
		for (ModelPart tatter : back) tatter.xRot -= this.hips.xRot * 0.7F;
	}

