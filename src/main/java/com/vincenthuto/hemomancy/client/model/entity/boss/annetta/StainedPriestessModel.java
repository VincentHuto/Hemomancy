	public void translateToHips(PoseStack poseStack) {
		this.root.translateAndRotate(poseStack);
		this.hips.translateAndRotate(poseStack);
	}

	/** Body space: where the wings tear out and the body tendrils root. */
	public void translateToBody(PoseStack poseStack) {
		translateToHips(poseStack);
		this.torso.translateAndRotate(poseStack);
		this.chest.translateAndRotate(poseStack);
		this.body.translateAndRotate(poseStack);
	}

	/** Head-knot space, following the head look, for the boiling tendrils and the eyes. */
	public void translateToHead(PoseStack poseStack) {
		translateToBody(poseStack);
		this.neckStump.translateAndRotate(poseStack);
		this.thornHead.translateAndRotate(poseStack);
	}

	public void translateToArm(HumanoidArm arm, PoseStack poseStack) {
		translateToBody(poseStack);
		(arm == HumanoidArm.LEFT ? this.leftArm : this.rightArm).translateAndRotate(poseStack);
	}

	public void translateToForearm(HumanoidArm arm, PoseStack poseStack) {
		translateToArm(arm, poseStack);
		(arm == HumanoidArm.LEFT ? this.leftForearm : this.rightForearm).translateAndRotate(poseStack);
	}

	/** The lancea's grip: -Z runs to the point. */
	public void translateToSpear(PoseStack poseStack) {
		translateToBody(poseStack);
		this.spear.translateAndRotate(poseStack);
	}

	@Override
	public void translateToHand(HumanoidArm arm, PoseStack poseStack) {
		translateToForearm(arm, poseStack);
		// Held-item layers measure ten pixels down from a shoulder; the grip is 5.2 down this forearm.
		poseStack.translate(0.0F, -4.8F / 16.0F, 0.0F);
	}
