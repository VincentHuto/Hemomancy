	/** Fast out of the gate and hard into the end: the snap of a thrust or a spin. */
	private static float snap(float t, float from, float to) {
		float x = Mth.clamp((t - from) / (to - from), 0.0F, 1.0F);
		return 1.0F - (1.0F - x) * (1.0F - x) * (1.0F - x);
	}

	private static float wrapLerp(float t, float a, float b) {
		return a + Mth.wrapDegrees((b - a) * Mth.RAD_TO_DEG) * Mth.DEG_TO_RAD * t;
	}

