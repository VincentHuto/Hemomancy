package com.vincenthuto.hemomancy.client.model.entity.mob.animal;

import com.vincenthuto.hemomancy.Hemomancy;
import com.vincenthuto.hemomancy.common.entity.mob.animal.FunglingEntity;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.util.Mth;

/**
 * Scuttles on diagonal pairs of feet with its cap wobbling a beat behind, turns its stalk and eye toward what it watches,
 * blinks, and throws its cap forward to bite or shove. The mesh is generated by tools/model_export/fungling.py.
 */
public final class FunglingModel extends HierarchicalModel<FunglingEntity> {
	public static final ModelLayerLocation LAYER_LOCATION = new ModelLayerLocation(Hemomancy.rloc("fungling"), "main");
	private static final float STRIDE_RATE = 1.5F;
	private static final int BLINK_PERIOD = 70;
	private static final int BLINK_TICKS = 4;

	private final ModelPart root;
	private final ModelPart body;
	private final ModelPart cap;
	private final ModelPart eye;
	private final Foot leftFront;
	private final Foot rightFront;
	private final Foot leftHind;
	private final Foot rightHind;

	private record Foot(ModelPart foot, ModelPart toe, float sign) {
		static Foot of(ModelPart body, String prefix, float sign) {
			ModelPart foot = body.getChild(prefix + "_foot");
			return new Foot(foot, foot.getChild(prefix + "_toe"), sign);
		}

		void stride(float phase, float amount) {
			float lift = Math.max(0.0F, Mth.sin(phase)) * amount;
			foot.yRot += sign * Mth.cos(phase) * 0.5F * amount;
			foot.zRot -= sign * lift * 0.45F;
			toe.zRot += sign * lift * 0.5F;
		}
	}

	public FunglingModel(ModelPart bakedRoot) {
		root = bakedRoot.getChild("root");
		body = root.getChild("body");
		cap = body.getChild("cap");
		eye = body.getChild("eye");
		leftFront = Foot.of(body, "left_front", 1.0F);
		rightFront = Foot.of(body, "right_front", -1.0F);
		leftHind = Foot.of(body, "left_hind", 1.0F);
		rightHind = Foot.of(body, "right_hind", -1.0F);
	}

	public static LayerDefinition createBodyLayer() {
		return FunglingMesh.createBodyLayer();
	}

	@Override
	public ModelPart root() {
		return root;
	}

	@Override
	public void setupAnim(FunglingEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
		root.getAllParts().forEach(ModelPart::resetPose);
		float amount = Math.min(limbSwingAmount, 1.0F);
		float phase = limbSwing * STRIDE_RATE;
		leftFront.stride(phase, amount);
		rightHind.stride(phase, amount);
		rightFront.stride(phase + Mth.PI, amount);
		leftHind.stride(phase + Mth.PI, amount);

		body.y -= Math.abs(Mth.sin(phase)) * 0.7F * amount;
		body.zRot += Mth.cos(phase) * 0.07F * amount;
		cap.zRot -= Mth.cos(phase - 0.9F) * 0.09F * amount;
		cap.xRot += Mth.sin(phase * 2.0F - 0.9F) * 0.04F * amount;

		float breath = Mth.sin(ageInTicks * 0.1F + entity.getId());
		cap.xScale += breath * 0.02F;
		cap.zScale += breath * 0.02F;
		cap.yScale -= breath * 0.02F;

		body.yRot += netHeadYaw * Mth.DEG_TO_RAD * 0.35F;
		eye.yRot += netHeadYaw * Mth.DEG_TO_RAD * 0.25F;
		eye.xRot += headPitch * Mth.DEG_TO_RAD * 0.4F;
		int blink = (entity.tickCount + entity.getId() * 13) % BLINK_PERIOD;
		if (blink < BLINK_TICKS) eye.yScale = 0.15F;

		float strike = Mth.sin(attackTime * Mth.PI);
		body.xRot -= strike * 0.35F;
		cap.xRot -= strike * 0.45F;
		float flinch = entity.hurtTime / 10.0F;
		cap.yScale -= flinch * 0.18F;
		cap.xScale += flinch * 0.1F;
		cap.zScale += flinch * 0.1F;
	}
}
