package com.vincenthuto.hemomancy.client.model.entity.mob.aquatic;

import com.vincenthuto.hemomancy.Hemomancy;
import com.vincenthuto.hemomancy.common.entity.mob.aquatic.HemojellyEntity;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.util.Mth;

/**
 * The bell contracts and relaxes, the tendrils trail it a beat behind, and a capture draws them in under the bell.
 * The mesh is generated by tools/model_export/hemojelly.py.
 */
public final class HemojellyModel extends HierarchicalModel<HemojellyEntity> {
	public static final ModelLayerLocation LAYER_LOCATION = new ModelLayerLocation(Hemomancy.rloc("hemojelly"), "main");
	private static final String[] JOINTS = {"middle", "lower", "tip"};
	private static final int TENDRILS = 8;
	private static final int ARMS = 4;

	private final ModelPart root;
	private final ModelPart bell;
	private final ModelPart heart;
	private final ModelPart[][] tendrils = new ModelPart[TENDRILS][JOINTS.length + 1];
	private final ModelPart[][] arms = new ModelPart[ARMS][2];

	public HemojellyModel(ModelPart bakedRoot) {
		super(RenderType::entityTranslucent);
		root = bakedRoot.getChild("root");
		bell = root.getChild("bell");
		heart = root.getChild("heart");
		for (int i = 0; i < TENDRILS; i++) {
			ModelPart joint = root.getChild("tendril" + i);
			tendrils[i][0] = joint;
			for (int j = 0; j < JOINTS.length; j++) {
				joint = joint.getChild("tendril" + i + "_" + JOINTS[j]);
				tendrils[i][j + 1] = joint;
			}
		}
		for (int i = 0; i < ARMS; i++) {
			arms[i][0] = root.getChild("arm" + i);
			arms[i][1] = arms[i][0].getChild("arm" + i + "_frill");
		}
	}

	public static LayerDefinition createBodyLayer() {
		return HemojellyMesh.createBodyLayer();
	}

	@Override
	public ModelPart root() {
		return root;
	}

	@Override
	public void setupAnim(HemojellyEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
		root.getAllParts().forEach(ModelPart::resetPose);
		float beat = ageInTicks * 0.15F + entity.getId();
		float squeeze = Math.max(0.0F, Mth.sin(beat));
		bell.xScale = bell.zScale = 1.0F - squeeze * 0.08F;
		bell.yScale = 1.0F + squeeze * 0.1F;
		heart.xScale = heart.zScale = 1.0F - squeeze * 0.05F;
		float lift = squeeze * 0.6F;
		bell.y -= lift;
		heart.y -= lift;

		float gather = entity.captureTicks() > 0 ? Mth.sin((30 - entity.captureTicks()) * Mth.PI / 60.0F) : 0.0F;
		for (int i = 0; i < TENDRILS; i++) {
			ModelPart base = tendrils[i][0];
			base.y -= lift;
			float inX = -Math.signum(base.x);
			float inZ = -Math.signum(base.z);
			base.xRot = Mth.sin(ageInTicks * 0.08F + i) * 0.06F + inZ * gather * 0.12F;
			base.zRot = Mth.cos(ageInTicks * 0.07F + i) * 0.06F - inX * gather * 0.12F;
			for (int j = 1; j < tendrils[i].length; j++) {
				ModelPart joint = tendrils[i][j];
				float trail = Mth.sin(beat - j * 0.7F) * 0.05F;
				joint.xRot = Mth.sin(ageInTicks * 0.09F + i + j) * 0.035F + trail + inZ * gather * 0.06F;
				joint.zRot = Mth.cos(ageInTicks * 0.08F + i + j) * 0.035F - inX * gather * 0.06F;
			}
		}
		for (int i = 0; i < ARMS; i++) {
			arms[i][0].y -= lift;
			arms[i][0].xRot = Mth.sin(beat - 0.5F + i) * 0.08F;
			arms[i][0].zRot = Mth.cos(ageInTicks * 0.06F + i) * 0.08F;
			arms[i][1].xRot = Mth.sin(beat - 1.2F + i) * 0.14F;
		}
	}
}
