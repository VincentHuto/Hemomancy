package com.vincenthuto.hemomancy.client.model.tile.crafting;

import static com.vincenthuto.hemomancy.client.model.tile.crafting.PuppeteersSpindleMesh.*;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.vincenthuto.hemomancy.Hemomancy;
import net.minecraft.client.model.Model;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.util.Mth;

/**
 * A Saxony spinning wheel grown from bone and muscle. Geometry is generated by
 * tools/model_export/puppeteers_spindle.py; the treadle, footman and crank form a solved linkage.
 */
public class PuppeteersSpindleModel extends Model {
    public static final ModelLayerLocation LAYER_LOCATION = new ModelLayerLocation(
            Hemomancy.rloc("puppeteers_spindle_model"), "main");
    private static final float WHEEL_SPEED = 0.06F;

    private final ModelPart body;
    private final ModelPart wheel;
    private final ModelPart heart;
    private final ModelPart flyer;
    private final ModelPart bobbin;
    private final ModelPart treadle;
    private final ModelPart footman;
    private final ModelPart fibre;

    public PuppeteersSpindleModel(ModelPart root) {
        super(RenderType::entityCutoutNoCull);
        this.body = root.getChild("body");
        this.wheel = this.body.getChild("wheel");
        this.heart = this.wheel.getChild("heart");
        this.flyer = this.body.getChild("flyer");
        this.bobbin = this.body.getChild("bobbin");
        this.treadle = this.body.getChild("treadle");
        this.footman = this.body.getChild("footman");
        this.fibre = this.body.getChild("fibre");
    }

    public static LayerDefinition createBodyLayer() {
        return PuppeteersSpindleMesh.create();
    }

    public void setupAnim(float ageInTicks) {
        float turn = ageInTicks * WHEEL_SPEED;
        this.wheel.zRot = turn;
        this.flyer.zRot = turn * FLYER_RATIO;
        this.bobbin.zRot = turn * (FLYER_RATIO - 0.4F);

        // Two quick beats per cycle, like a pulse rather than a sine breath.
        float beat = Mth.sin(ageInTicks * 0.21F);
        float pulse = 1.0F + 0.07F * beat * beat * beat * beat;
        this.heart.xScale = this.heart.yScale = this.heart.zScale = pulse;
        this.fibre.zRot = Mth.sin(ageInTicks * 0.05F) * 0.025F;

        // The crank pin drives the treadle tip; the footman spans the two every frame.
        float pinX = HUB_X + CRANK_RADIUS * Mth.cos(turn);
        float pinY = HUB_Y + CRANK_RADIUS * Mth.sin(turn);
        float treadleAngle = (float) Math.asin((pinY - HUB_Y) * TREADLE_TRAVEL / TREADLE_REACH);
        this.treadle.zRot = treadleAngle;
        float dx = HINGE_X + TREADLE_REACH * Mth.cos(treadleAngle) - pinX;
        float dy = HINGE_Y + TREADLE_REACH * Mth.sin(treadleAngle) - pinY;
        this.footman.x = pinX;
        this.footman.y = pinY;
        this.footman.zRot = (float) Mth.atan2(-dx, dy);
        this.footman.yScale = Mth.sqrt(dx * dx + dy * dy) / FOOTMAN_LENGTH;
    }

    @Override
    public void renderToBuffer(PoseStack poseStack, VertexConsumer vertexConsumer, int packedLight, int packedOverlay,
                               int packedColor) {
        this.body.render(poseStack, vertexConsumer, packedLight, packedOverlay, packedColor);
    }
}
