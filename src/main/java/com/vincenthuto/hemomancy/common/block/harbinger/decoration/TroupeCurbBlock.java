package com.vincenthuto.hemomancy.common.block.harbinger.decoration;

import com.vincenthuto.hemomancy.common.block.shared.ModelShapes;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.util.Mth;
import net.minecraft.world.item.context.BlockPlaceContext;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Mirror;
import net.minecraft.world.level.block.Rotation;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.IntegerProperty;
import net.minecraft.world.phys.shapes.CollisionContext;
import net.minecraft.world.phys.shapes.VoxelShape;

/**
 * The Crimson Troupe's ring curb: one piece in eight rotations, 45 degree steps clockwise from north, so a ring can
 * follow its diagonals. Even steps show the straight model and odd steps the diagonal one; both are generated by
 * tools/model_export/circus_set_pieces.py and placed by the circus kit's ring.
 */
public class TroupeCurbBlock extends Block {
	public static final IntegerProperty ROTATION = IntegerProperty.create("rotation", 0, 7);
	private static final Direction[] STRAIGHT = { Direction.NORTH, Direction.EAST, Direction.SOUTH, Direction.WEST };
	private static final VoxelShape DIAGONAL = ModelShapes.of(new double[] { 2, 0, 2, 14, 6.5, 14 });
	private final VoxelShape[] shapes = new VoxelShape[8];

	public TroupeCurbBlock(Properties properties) {
		super(properties);
		VoxelShape north = ModelShapes.of(new double[] { 0, 0, 4.25, 16, 7, 11.75 });
		for (int step = 0; step < 8; step++)
			shapes[step] = step % 2 == 0 ? ModelShapes.rotate(north, STRAIGHT[step / 2]) : DIAGONAL;
		registerDefaultState(stateDefinition.any().setValue(ROTATION, 0));
	}

	@Override
	protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
		builder.add(ROTATION);
	}

	/** Faces the placer: a yaw of 0 looks south, so the step toward the player is the yaw in 45 degree steps. */
	@Override
	public BlockState getStateForPlacement(BlockPlaceContext context) {
		return defaultBlockState().setValue(ROTATION, Mth.floor(context.getRotation() / 45.0F + 0.5F) & 7);
	}

	@Override
	protected BlockState rotate(BlockState state, Rotation rotation) {
		return state.setValue(ROTATION, (state.getValue(ROTATION) + 2 * rotation.ordinal()) & 7);
	}

	/** LEFT_RIGHT swaps north and south, FRONT_BACK swaps east and west. */
	@Override
	protected BlockState mirror(BlockState state, Mirror mirror) {
		int step = state.getValue(ROTATION);
		return switch (mirror) {
			case LEFT_RIGHT -> state.setValue(ROTATION, (12 - step) & 7);
			case FRONT_BACK -> state.setValue(ROTATION, (8 - step) & 7);
			default -> state;
		};
	}

	@Override
	protected VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
		return shapes[state.getValue(ROTATION)];
	}
}
