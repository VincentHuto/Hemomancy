package com.vincenthuto.hemomancy.client.model.entity.boss.endgame;

import org.junit.jupiter.api.Test;

import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

final class MycophantModelSourceTest {
	private static final Path SOURCE = Path.of("src/main/java/com/vincenthuto/hemomancy");
	private static final Path TEXTURES = Path.of("src/main/resources/assets/hemomancy/textures/entity/boss/endgame");

	@Test
	void theSpawnMotherModelIsGeneratedWithItsPhaseTwoAnatomy() throws Exception {
		String model = Files.readString(SOURCE.resolve("client/model/entity/boss/endgame/MycophantModel.java"));
		assertTrue(model.contains("Generated by tools/model_export/mycophant.py"));
		for (String part : new String[] { "skullHalfL", "skullHalfR", "pulp", "wingL", "wingR", "collarHinges",
				"siphon", "sacShell", "clawFrontLUpper", "armHandUpper", "cradledFungling", "renderSacShell" })
			assertTrue(model.contains(part), part);
		assertFalse(model.contains("Uzouthrhix"));
		assertFalse(model.contains("armTent"));
		assertTrue(Files.exists(Path.of("tools/model_export/mycophant.py")));
		assertTrue(Files.exists(Path.of("tools/model_export/mycophant_anim.java")));
		assertTrue(Files.exists(Path.of("tools/model_export/reference/spawn-mother-v8.html")));
	}

	@Test
	void theRendererDrawsTheGlowAndTheSacInsteadOfTheAwokenSwap() throws Exception {
		String renderer = Files.readString(SOURCE.resolve("client/render/entity/boss/endgame/MycophantRenderer.java"));
		assertFalse(renderer.contains("mycophant_awoken"));
		assertTrue(renderer.contains("new MycophantGlowLayer(this)"));
		assertTrue(renderer.contains("new MycophantSacLayer(this)"));
		assertTrue(renderer.contains("getFlipDegrees"));
		assertTrue(Files.exists(TEXTURES.resolve("mycophant.png")));
		assertTrue(Files.exists(TEXTURES.resolve("mycophant_glow.png")));
		assertTrue(Files.exists(TEXTURES.resolve("mycophant_sac.png")));
		assertFalse(Files.exists(TEXTURES.resolve("mycophant_awoken.png")));
	}
}
