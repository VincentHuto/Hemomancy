package com.vincenthuto.hemomancy.client.render.entity.boss.annetta;

import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

class AnnettaModelSourceTest {
    private static final String ENTITY = "src/main/java/com/vincenthuto/hemomancy/common/entity/boss/annetta/";
    private static final String MODEL = "src/main/java/com/vincenthuto/hemomancy/client/model/entity/boss/annetta/";

    private static String read(String path) throws IOException {
        return Files.readString(Path.of(path)).replace("\r\n", "\n");
    }

    private static String method(String source, String signature) {
        int start = source.indexOf(signature);
        assertTrue(start >= 0, "missing " + signature);
        int open = source.indexOf('{', start);
        int depth = 0;
        for (int i = open; i < source.length(); i++) {
            if (source.charAt(i) == '{') depth++;
            if (source.charAt(i) == '}' && --depth == 0) return source.substring(start, i + 1);
        }
        throw new AssertionError("unbalanced " + signature);
    }

    @Test
    void equippedRenderItemsNeverDrop() throws IOException {
        String annetta = read(ENTITY + "AnnettaKnowlesEntity.java");
        assertTrue(method(annetta, "private void startHarbingerRoute").contains("ItemInit.annettas_absolution_dagger.get()"));
        // On the cure route she takes up her dagger once the purge is over.
        assertTrue(method(annetta, "private void tickPurge").contains("ItemInit.annettas_absolution_dagger.get()"));
        assertTrue(annetta.contains("setDropChance(EquipmentSlot.MAINHAND, 0.0F)"));
        assertFalse(annetta.contains("ItemInit.absolution_dagger.get()"));
        // Old saves restore HandDropChances after construction, so each equip sets its own chance too.
        assertTrue(method(annetta, "private void startHarbingerRoute").contains("setDropChance(EquipmentSlot.MAINHAND, 0.0F)"));
        assertTrue(method(annetta, "private void tickPurge").contains("setDropChance(EquipmentSlot.MAINHAND, 0.0F)"));
        assertTrue(annetta.contains("setLeftHanded(false)"), "her dagger must stay in the right hand");
    }

    @Test
    void phaseOneCarriesTheRealUnstainedShield() throws IOException {
        String harbinger = method(read(ENTITY + "AnnettaKnowlesEntity.java"), "private void startHarbingerRoute");
        assertTrue(harbinger.contains("setItemSlot(EquipmentSlot.OFFHAND, new ItemStack(ItemInit.unstained_shield.get()))"));
        assertTrue(harbinger.contains("setDropChance(EquipmentSlot.OFFHAND, 0.0F)"));
        String model = read(MODEL + "AnnettaKnowlesModel.java");
        assertFalse(model.contains("cracked_shield"), "no invented shield geometry");
    }

    @Test
    void heldLanceaAddsNoDamage() throws IOException {
        String priestess = read(ENTITY + "StainedPriestessEntity.java");
        assertTrue(priestess.contains("DataComponents.ATTRIBUTE_MODIFIERS, ItemAttributeModifiers.EMPTY"),
                "the held lancea must not add its +6 attack to her documented 12");
    }

    private static String registration(String entityInit, String id) {
        int start = entityInit.indexOf("\"" + id + "\",");
        assertTrue(start >= 0, "missing registration " + id);
        return entityInit.substring(start, entityInit.indexOf(";", start));
    }

    @Test
    void priestessSizedAndArmed() throws IOException {
        String init = read("src/main/java/com/vincenthuto/hemomancy/common/init/EntityInit.java");
        assertTrue(registration(init, "stained_priestess").contains(".sized(0.9F, 2.2F)"));
        String priestess = read(ENTITY + "StainedPriestessEntity.java");
        assertTrue(priestess.contains("ItemStack lancea = new ItemStack(ItemInit.annettas_sanguis_lancea.get())"));
        assertTrue(priestess.contains("setItemSlot(EquipmentSlot.MAINHAND, lancea)"));
        assertTrue(priestess.contains("setDropChance(EquipmentSlot.MAINHAND, 0.0F)"));
    }

    @Test
    void priestessCullingCoversWings() throws IOException {
        String priestess = read(ENTITY + "StainedPriestessEntity.java");
        String culling = method(priestess, "public AABB getBoundingBoxForCulling()");
        assertTrue(culling.contains("inflate(5.5D"), "wings reach about five blocks past the body");
    }

    @Test
    void priestessHasNoCopper() throws IOException {
        String script = read("tools/model_export/stained_priestess.py");
        assertFalse(script.contains("verdigris("));
        assertFalse(script.contains("'copper'"));
        String model = read(MODEL + "StainedPriestessModel.java");
        assertTrue(model.contains("Generated by tools/model_export/stained_priestess.py"));
        for (String part : new String[]{"thorn_head", "neck_stump"}) {
            assertTrue(model.contains('"' + part + '"'), part);
        }
        // Wings and head are living tendrils now, not box parts.
        assertFalse(model.contains("\"left_wing_0\""));
        assertFalse(model.contains("thorn_spike_"));
        String renderer = read("src/main/java/com/vincenthuto/hemomancy/client/render/entity/boss/annetta/StainedPriestessRenderer.java");
        assertTrue(renderer.contains("new StainedPriestessTendrilLayer(this)"));
    }

    @Test
    void latentSizedAndNoCopper() throws IOException {
        String init = read("src/main/java/com/vincenthuto/hemomancy/common/init/EntityInit.java");
        assertTrue(registration(init, "latent_annetta_infection").contains(".sized(1.6F, 4.5F)"));
        String script = read("tools/model_export/latent_annetta_infection.py");
        assertFalse(script.contains("verdigris("));
        assertFalse(script.contains("'copper'"));
        String model = read(MODEL + "LatentAnnettaInfectionModel.java");
        assertTrue(model.contains("Generated by tools/model_export/latent_annetta_infection.py"));
        for (String part : new String[]{"tail_7", "whip_arm_7", "upper_claw_arm", "lower_claw_arm", "head_mass", "spear"}) {
            assertTrue(model.contains('"' + part + '"'), part);
        }
    }

    @Test
    void cureRouteChecksInfectionSpace() throws IOException {
        String annetta = read(ENTITY + "AnnettaKnowlesEntity.java");
        assertTrue(method(annetta, "private boolean placeInfection").contains("roomFor(server, infection)"));
        assertTrue(method(annetta, "private boolean roomFor").contains("noCollision(infection"));
        String cure = method(annetta, "private void startCureRoute");
        int check = cure.indexOf("placeInfection(server, infection)");
        int add = cure.indexOf("addFreshEntity(infection)");
        int shrink = cure.indexOf("brewStack.shrink(1)");
        assertTrue(check >= 0, "the infection's new box must be checked for room");
        assertTrue(check < add && add < shrink, "room is found before spawning and before the draught is spent");
        assertTrue(method(annetta, "private boolean roomFor").contains("ClipContext"), "no spawning behind walls");
        assertTrue(cure.contains("hemomancy.annetta.event.no_room"), "say why nothing happened");
        String infection = read(ENTITY + "LatentAnnettaInfectionEntity.java");
        assertTrue(method(infection, "public AABB getBoundingBoxForCulling()").contains("inflate("));
    }

    @Test
    void generatedModelHasRig() throws IOException {
        String model = read(MODEL + "AnnettaKnowlesModel.java");
        assertTrue(model.contains("Generated by tools/model_export/annetta_knowles.py"));
        for (String part : new String[]{"neck_tick", "tick_abdomen", "long_hair", "short_hair"}) {
            assertTrue(model.contains('"' + part + '"'), part);
        }
        assertTrue(model.contains("implements ArmedModel"));
    }
}
